#!/usr/bin/env python3

# Generate the proofs.mk of a build of mlkem-native's libmlkem.so, which
# arm/Makefile includes (see mlkem_native/README.md): the object files of
# the transcriptions in mlkem_native/<build>, the proofs in
# proofs/mlkem_native/<build> that are only about the whole image, and the
# dependencies of each proof on the files that it loads with `needs`.
#
# Usage, in s2n-bignum's arm directory:
#
#   python3 mlkem_native/gen_proofs_mk.py gcc12_O2 > mlkem_native/gcc12_O2/proofs.mk

import os, re, sys

def main():
    if len(sys.argv) != 2:
        sys.exit('usage: gen_proofs_mk.py BUILD')
    build = sys.argv[1]
    src = 'mlkem_native/%s' % build
    prf = 'proofs/mlkem_native/%s' % build
    objs = sorted(f[:-2] for f in os.listdir(src) if f.endswith('.S'))
    proofs = sorted(f[:-3] for f in os.listdir(prf)
                    if f.endswith('.ml') and f != 'layout.ml')
    image = [p for p in proofs if p not in objs]
    missing = [o for o in objs if o not in proofs]
    if missing:
        sys.exit('gen_proofs_mk.py: no proofs for ' + ' '.join(missing))
    out = ['# Generated by mlkem_native/gen_proofs_mk.py %s from the needs of the' % build,
           '# proofs in %s. Do not edit.' % prf, '']
    def lst(var, items, sfx):
        out.append('%s += \\' % var)
        for i, x in enumerate(items):
            out.append('  %s/%s%s%s' % (src, x, sfx, ' \\' if i + 1 < len(items) else ''))
        out.append('')
    lst('MLKEM_NATIVE_OBJ', objs, '.o')
    if image:
        lst('MLKEM_NATIVE_IMAGE_PROOFS', image, '')
    def needs(path):
        if not os.path.exists(path):
            return []
        return [m.group(1) for l in open(path)
                for m in [re.match(r'\s*needs\s+"arm/(proofs/[^"]+)"', l)] if m]
    for p in proofs:
        # The other proofs it loads (as .native files, which depend on what
        # they load in turn), and the other files it loads directly or
        # through those files, since they are not targets of make
        deps = []; todo = needs('%s/%s.ml' % (prf, p))
        while todo:
            d = todo.pop(0)
            if d.startswith(prf + '/') and d != prf + '/layout.ml':
                n = '%s/%s.native' % (src, d[len(prf) + 1:-3])
                if n not in deps:
                    deps.append(n)
            elif d.startswith('proofs/utils/') or d.startswith('proofs/mlkem_native/'):
                if d not in deps:
                    deps.append(d); todo += needs(d)
        if deps:
            out.append('%s/%s.native: \\' % (src, p))
            out += ['  %s%s' % (d, ' \\' if i + 1 < len(deps) else '') for i, d in enumerate(deps)]
    sys.stdout.write('\n'.join(out) + '\n')

if __name__ == '__main__':
    main()
