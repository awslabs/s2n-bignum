(* ========================================================================= *)
(* The slots of libplt_demo.so (the test library libplt_demo.so) that the    *)
(* dynamic loader relocates, with the values that it writes there when it    *)
(* loads the binary at the base pc, the address of each imported symbol      *)
(* "sym" being imp "sym". 5 relocations. Generated by tools/elf_relocs.py    *)
(* (which explains the format) from the binary with SHA-256                  *)
(* 8b5a764681229d61b4941ff4642962e155b73cac346b2e2864ab9d74080489e9. Do not  *)
(* edit it by hand.                                                          *)
(* ========================================================================= *)

needs "Library/words.ml";;

(* The relocations, as offset, type, symbol + addend:                        *)
(*                                                                           *)
(*   0x1fe48  R_AARCH64_RELATIVE   0x370                                     *)
(*   0x1fe50  R_AARCH64_ABS64      memmove + 0x8                             *)
(*   0x1ffe0  R_AARCH64_JUMP_SLOT  memmove + 0x0                             *)
(*   0x1ffe8  R_AARCH64_JUMP_SLOT  memcpy + 0x0                              *)
(*   0x1fff8  R_AARCH64_GLOB_DAT   memcpy + 0x0                              *)

let plt_demo_relocated = new_definition
 `plt_demo_relocated (pc:num) (imp:string->int64) =
   [(word (pc + 0x1fe48):int64, word (pc + 0x370):int64);
    (word (pc + 0x1fe50):int64, word_add (imp "memmove") (word 0x8):int64);
    (word (pc + 0x1ffe0):int64, imp "memmove":int64);
    (word (pc + 0x1ffe8):int64, imp "memcpy":int64);
    (word (pc + 0x1fff8):int64, imp "memcpy":int64)]`;;
