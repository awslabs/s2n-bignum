(* symbols that the functions load with ADRP and LDR: for a function f,      *)
(* f_consts is the block of all of them and, if there are several, f_constK  *)
(* is the K-th one. The linker merges equal constants, so some have several  *)
(* names. plt_g and got_g are the entry of the procedure linkage table and   *)
(* the slot of the global offset table (GOT, which is not part of the image) *)
(* for an external symbol g, and libmlkem_size is the size of the image,     *)
(* from address 0 to the end of the read-only data.                          *)
