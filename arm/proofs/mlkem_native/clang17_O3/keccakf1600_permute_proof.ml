  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN `val(word (2 * i):int64) = 2 * i` SUBST1_TAC THENL
   [MATCH_MP_TAC VAL_WORD_EQ THEN REWRITE_TAC[DIMINDEX_64] THEN
    CONV_TAC NUM_REDUCE_CONV THEN ASM_ARITH_TAC;
    ASM_ARITH_TAC]);;

let MLKEM_NATIVE_KECCAKF1600_PERMUTE_CLANG17_O3_IMAGE_SUBROUTINE_FULL_RC = prove
 (MLKEM_NATIVE_KECCAKF1600_PERMUTE_CLANG17_O3_IMAGE_SUBROUTINE_FULL_RC_STMT,
  PERMUTE_CS_INTRO_TAC THEN
  FIRST_X_ASSUM(fun rcth ->
    if concl rcth = `rc = pc + rodata_mlk_KeccakF_RoundConstants`
    then
      ENSURES_EVENTS_WHILE_UP2_TAC `12` `pc + mlkem_keccakf1600_permute_loop1`
       `pc + mlkem_keccakf1600_permute_loop1_exit`
       keccak_inv_cs THEN
      REPEAT CONJ_TAC THENL
       [ARITH_TAC;
        PERMUTE_CS_INIT_TAC rcth;
        PERMUTE_CS_BODY1_TAC rcth THEN PERMUTE_CS_BODY2_TAC;
        PERMUTE_CS_TAIL_TAC]
    else NO_TAC));;

