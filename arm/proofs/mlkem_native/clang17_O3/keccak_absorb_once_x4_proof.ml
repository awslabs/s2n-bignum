    ASM_CASES_TAC `mlen < r` THEN ASM_REWRITE_TAC[] THEN
    ABSX4_CS_TAIL_TAC]);;

let MLKEM_NATIVE_KECCAK_ABSORB_ONCE_X4_CLANG17_O3_IMAGE_SUBROUTINE_CORRECT = prove
 (MLKEM_NATIVE_KECCAK_ABSORB_ONCE_X4_CLANG17_O3_IMAGE_SUBROUTINE_CORRECT_STMT,
  REPEAT STRIP_TAC THEN
  X_CHOOSE_TAC
