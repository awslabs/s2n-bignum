needs "arm/proofs/mlkem_native/clang17_O3/enc_derand_k3_spec.ml";;


let MLKEM_EK_CHECK_768 = prove
 (MLKEM_EK_CHECK_768_STMT,
  SIMP_TAC[mlkem768; MLKEM_EK_CHECK] THEN CONV_TAC NUM_REDUCE_CONV);;

let KE3_CHECK_EQ = prove
 (KE3_CHECK_EQ_STMT,
  GEN_TAC THEN AP_TERM_TAC THEN ABS_TAC THEN
  MATCH_MP_TAC(TAUT `(p ==> (q <=> r)) ==> (p ==> q <=> p ==> r)`) THEN
  DISCH_TAC THEN AP_THM_TAC THEN AP_TERM_TAC THEN
  MATCH_MP_TAC DIV_MOD_EXP_LOW THEN ASM_ARITH_TAC);;

let KE3_BUFFER_ADDRESS = prove
 (KE3_BUFFER_ADDRESS_STMT,
  REWRITE_TAC[REJ_ALIGNED_16_32] THEN GEN_TAC THEN
  COND_CASES_TAC THEN POP_ASSUM MP_TAC THEN
  W(fun (_,w) -> ACCEPT_TAC(BITBLAST_RULE w)));;

let MLKEM_NATIVE_ENC_DERAND_K3_CLANG17_O3_IMAGE_SUBROUTINE_CORRECT = prove
 (MLKEM_NATIVE_ENC_DERAND_K3_CLANG17_O3_IMAGE_SUBROUTINE_CORRECT_STMT,
  KE3_INTRO_TAC THEN
  PAR_THENL (ASM_CASES_TAC `aligned 32 (stackpointer:int64)`)
   [KE3_CASE_TAC 16672; KE3_CASE_TAC 16656]);;


let MLKEM_NATIVE_ENC_DERAND_K3_CLANG17_O3_IMAGE_SUBROUTINE_SAFE = prove
 (MLKEM_NATIVE_ENC_DERAND_K3_CLANG17_O3_IMAGE_SUBROUTINE_SAFE_STMT,
  KE3_SAFE_INTRO_TAC THEN
  PAR_THENL (ASM_CASES_TAC `aligned 32 (stackpointer:int64)`)
   [KE3_SAFE_CASE_TAC 16672; KE3_SAFE_CASE_TAC 16656]);;
