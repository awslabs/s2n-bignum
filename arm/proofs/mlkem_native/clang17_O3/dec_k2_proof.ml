let KPKE_ENCRYPT_LENGTH_512 = prove
 (KPKE_ENCRYPT_LENGTH_512_STMT,
  REWRITE_TAC[mlkem512; KPKE_ENCRYPT_LENGTH] THEN CONV_TAC NUM_REDUCE_CONV);;

let KPKE_DECRYPT_LENGTH_512 = prove
 (KPKE_DECRYPT_LENGTH_512_STMT,
  REWRITE_TAC[mlkem512; KPKE_DECRYPT_LENGTH]);;

let KD2_CHECK = prove
 (KD2_CHECK_STMT,
  REPEAT STRIP_TAC THEN REWRITE_TAC[mlkem512; mlkem_decaps_check] THEN
  CONV_TAC NUM_REDUCE_CONV THEN ASM_REWRITE_TAC[mlkem_h] THEN
  CONV_TAC(LAND_CONV SYM_CONV) THEN CONV_TAC SYM_CONV THEN
  MATCH_MP_TAC NUM_OF_BYTELIST_INJ THEN
  REWRITE_TAC[mlkem_slice; LENGTH_LIST_OF_SEQ; LENGTH_SHA3_256]);;

let KD2_ALIGNED_16_32 = prove
 (KD2_ALIGNED_16_32_STMT,
  CONJ_TAC THEN GEN_TAC THEN REWRITE_TAC[aligned; DIMINDEX_64] THEN
  CONV_TAC NUM_REDUCE_CONV THEN
  CONV_TAC(ONCE_DEPTH_CONV DIVIDES_CONV) THEN REWRITE_TAC[] THENL
   [MP_TAC(ISPECL [`x:int64`; `4`] (CONJUNCT1 WORD_AND_MASK_WORD));
    MP_TAC(ISPECL [`x:int64`; `5`] (CONJUNCT1 WORD_AND_MASK_WORD))] THEN
  CONV_TAC(ONCE_DEPTH_CONV NUM_REDUCE_CONV) THEN DISCH_THEN SUBST1_TAC THEN
  REWRITE_TAC[DIVIDES_MOD; GSYM VAL_EQ_0; VAL_WORD; DIMINDEX_64] THEN
  SIMP_TAC[MOD_LT; ARITH_RULE `x MOD 16 < 16`; ARITH_RULE `x MOD 32 < 32`;
           ARITH_RULE `x < 16 ==> x < 2 EXP 64`;
           ARITH_RULE `x < 32 ==> x < 2 EXP 64`]);;

let KD2_BUFFER_ADDRESS = prove
 (KD2_BUFFER_ADDRESS_STMT,
  REWRITE_TAC[KD2_ALIGNED_16_32] THEN GEN_TAC THEN
  COND_CASES_TAC THEN POP_ASSUM MP_TAC THEN
  W(fun (_,w) -> ACCEPT_TAC(BITBLAST_RULE w)));;

let KD2_CMOV_TEST = prove
 (KD2_CMOV_TEST_STMT,
  REPEAT STRIP_TAC THEN REWRITE_TAC[VAL_WORD_ADD; VAL_WORD; DIMINDEX_64] THEN
  CONV_TAC NUM_REDUCE_CONV THEN
  SUBGOAL_THEN `i MOD 18446744073709551616 = i` SUBST1_TAC THENL
   [MATCH_MP_TAC MOD_LT THEN ASM_ARITH_TAC; ALL_TAC] THEN
  ASM_CASES_TAC `i + 1 < 32` THEN ASM_REWRITE_TAC[] THENL
   [MATCH_MP_TAC(ARITH_RULE `~(x = 0) /\ x MOD n = x ==> ~(x MOD n = 0)`) THEN
    CONJ_TAC THENL [ARITH_TAC; MATCH_MP_TAC MOD_LT THEN ASM_ARITH_TAC];
    SUBGOAL_THEN `i = 31` SUBST1_TAC THENL [ASM_ARITH_TAC; ALL_TAC] THEN
    CONV_TAC NUM_REDUCE_CONV]);;

let KD2_MOD_ALL = prove
 (KD2_MOD_ALL_STMT,
  REPEAT GEN_TAC THEN SPEC_TAC(`k:num`,`k:num`) THEN INDUCT_TAC THENL
   [REWRITE_TAC[MULT_CLAUSES; EXP; MOD_1; LT]; ALL_TAC] THEN
  REWRITE_TAC[ARITH_RULE `SUC k = k + 1`] THEN
  ASM_REWRITE_TAC[KEM_MOD_STEP] THEN
  REWRITE_TAC[ARITH_RULE `!j. j < k + 1 <=> j < k \/ j = k`] THEN
  MESON_TAC[]);;

