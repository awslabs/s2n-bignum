      (word((if aligned 32 stackpointer then 1824 else 1840) + 960))`;
    `33`; `guard:int64`; `pc:num`; `read SP s`; `read X30 s`] 46 THEN
  MAP_EVERY (fun (k,name) ->
    ARM_STEPS_TAC MLKEM_NATIVE_POLY_GETNOISE_ETA1122_4X_K2_GCC12_O3_EXEC
     ((k-3)--(k-1)) THEN
    GETNOISE4_SAFE_CALL_TAC name
     ([`e:(uarch_event)list`; `read X0 s`; `read X1 s`; `pc:num`] @
      (if name = "H_CBD3" then [`read SP s`] else []) @
      [`read X30 s`]) k)
   [50,"H_CBD3"; 54,"H_CBD3"; 58,"H_CBD2"; 62,"H_CBD2"] THEN
  ARM_STEPS_TAC MLKEM_NATIVE_POLY_GETNOISE_ETA1122_4X_K2_GCC12_O3_EXEC
   (63--66) THEN
