let KECCAK_ABSORB_FROM_0 = prove
 (KECCAK_ABSORB_FROM_0_STMT,
  GEN_TAC THEN GEN_TAC THEN INDUCT_TAC THEN
  ASM_REWRITE_TAC[keccak_absorb_from; keccak_absorb]);;

