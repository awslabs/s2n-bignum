    can (term_match [] `read (bytes16 a) s = x`) (concl th))) THEN
  REWRITE_TAC[BYTES16_WBYTES; VAL_READ_WBYTES; DIMINDEX_16] THEN
  CONV_TAC NUM_REDUCE_CONV THEN REWRITE_TAC[DIMINDEX_16] THEN ARITH_TAC);;

