let MLKEM_NATIVE_POLY_MULCACHE_COMPUTE_GCC12_O3_IMAGE_SUBROUTINE_CORRECT = prove
 (MLKEM_NATIVE_POLY_MULCACHE_COMPUTE_GCC12_O3_IMAGE_SUBROUTINE_CORRECT_STMT,
  MAP_EVERY X_GEN_TAC [`dst:int64`; `src:int64`; `x:num->int16`; `pc:num`] THEN
  WORD_FORALL_OFFSET_TAC 16 THEN
  MAP_EVERY X_GEN_TAC [`stackpointer:int64`; `returnaddress:int64`] THEN
  REWRITE_TAC[MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI; C_ARGUMENTS;
              NONOVERLAPPING_CLAUSES; ALL] THEN
  DISCH_THEN(REPEAT_TCL CONJUNCTS_THEN ASSUME_TAC) THEN
  ENSURES_EXISTING_PRESERVED_TAC `SP` THEN
  ENSURES_PRESERVED_DREG_TAC "d8_init" `D8` THEN
  ENSURES_EXISTING_PRESERVED_TAC `X30` THEN
  ENSURES_INIT_TAC "s0" THEN

  (*** The check for overlap, which goes to the vector code ***)

  MP_TAC(SPECL [`dst:int64`; `src:int64`] MULCACHE_ALIAS) THEN
  ANTS_TAC THENL [ASM_REWRITE_TAC[NONOVERLAPPING_CLAUSES]; DISCH_TAC] THEN
  ARM_STEPS_TAC MLKEM_NATIVE_POLY_MULCACHE_COMPUTE_GCC12_O3_EXEC (1--6) THEN
  FIRST_X_ASSUM(fun th -> if is_cond(concl th) then
    RULE_ASSUM_TAC(REWRITE_RULE[th]) else failwith "") THEN

  (*** The facts for the input and the constants ***)

  MC_LOAD_FACTS_TAC THEN MC_MERGE_TAC `s6:armstate` THEN
  MAP_EVERY (fun th -> FIRST_ASSUM(ASSUME_TAC o MATCH_MP th))
    MLKEM_NATIVE_POLY_MULCACHE_COMPUTE_GCC12_O3_CONSTANTS THEN

  (*** The straight-line code, ending with the return ***)

  MAP_EVERY mc_step_tac (7--235) THEN

  (*** The outputs ***)

  MC_DST_CLEAN_TAC THEN
  ENSURES_FINAL_STATE_TAC THEN ASM_REWRITE_TAC[] THEN
  CONJ_TAC THENL [ALL_TAC; REWRITE_TAC[WORD_ZX_ZX_64]] THEN
  MC_SPLIT_TAC THEN MC_DISCARD_SRC_TAC THEN
  X_GEN_TAC `i:num` THEN DISCH_TAC THEN
  UNDISCH_TAC `i < 128` THEN SPEC_TAC(`i:num`,`i:num`) THEN
  CONV_TAC EXPAND_CASES_CONV THEN CONV_TAC NUM_REDUCE_CONV THEN
  REWRITE_TAC[WORD_ADD_0] THEN CONV_TAC(TOP_DEPTH_CONV let_CONV) THEN
  ASM_REWRITE_TAC[] THEN
  REPEAT(CONJ_TAC THENL [MC_LANE_TAC; ALL_TAC]) THEN MC_LANE_TAC);;

let MLKEM_NATIVE_POLY_MULCACHE_COMPUTE_GCC12_O3_IMAGE_SUBROUTINE_SAFE = time prove
 (MLKEM_NATIVE_POLY_MULCACHE_COMPUTE_GCC12_O3_IMAGE_SUBROUTINE_SAFE_STMT,
  ASSERT_CONCL_TAC full_spec THEN
  CONCRETIZE_F_EVENTS_TAC
    `\(src:int64) (dst:int64) (pc:num) (sp:int64) (returnaddress:int64).
      f_ev src dst pc sp returnaddress:(uarch_event)list` THEN
  REPEAT META_EXISTS_TAC THEN STRIP_TAC THEN
  REPEAT_GEN_AND_OFFSET_STACKPTR_TAC THEN
  REWRITE_TAC[C_ARGUMENTS; NONOVERLAPPING_CLAUSES; ALL;
              MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI] THEN
  REPEAT STRIP_TAC THEN
  RULE_ASSUM_TAC(CONV_RULE(TRY_CONV NORMALIZE_ALIGNED_WORD_CONV)) THEN
  ENSURES_EXISTING_PRESERVED_TAC `SP` THEN
  ENSURES_PRESERVED_DREG_TAC "d8_init" `D8` THEN
  ENSURES_EXISTING_PRESERVED_TAC `X30` THEN
  REWRITE_TAC(!simulation_precanon_thms) THEN
  ENSURES_INIT_TAC "s0" THEN TRY STRIP_EXISTS_ASSUM_TAC THEN

  (*** The check for overlap, which goes to the vector code ***)

  MP_TAC(SPECL [`dst:int64`; `src:int64`] MULCACHE_ALIAS) THEN
  ANTS_TAC THENL [ASM_REWRITE_TAC[NONOVERLAPPING_CLAUSES]; DISCH_TAC] THEN
  ARM_STEPS_TAC MLKEM_NATIVE_POLY_MULCACHE_COMPUTE_GCC12_O3_EXEC (1--6) THEN
  FIRST_X_ASSUM(fun th -> if is_cond(concl th) then
    RULE_ASSUM_TAC(REWRITE_RULE[th]) else failwith "") THEN

  (*** The straight-line code, ending with the return ***)

  MAP_EVERY (fun (a,b) ->
    ARM_STEPS_TAC MLKEM_NATIVE_POLY_MULCACHE_COMPUTE_GCC12_O3_EXEC (a--b) THEN
    (if b < 235 then MLKEM_NATIVE_ADRP_TAC else ALL_TAC)) mc_safe_ranges THEN
  ENSURES_FINAL_STATE_TAC THEN ASM_REWRITE_TAC[WORD_ZX_ZX_64] THEN
  DISCHARGE_SAFETY_PROPERTY_TAC);;
