needs "arm/proofs/mlkem_native/gcc12_O3/dec_k2_spec.ml";;


let KPKE_ENCRYPT_LENGTH_512 = prove
 (KPKE_ENCRYPT_LENGTH_512_STMT,
  REWRITE_TAC[mlkem512; KPKE_ENCRYPT_LENGTH] THEN CONV_TAC NUM_REDUCE_CONV);;

let KPKE_DECRYPT_LENGTH_512 = prove
 (KPKE_DECRYPT_LENGTH_512_STMT,
  REWRITE_TAC[mlkem512; KPKE_DECRYPT_LENGTH]);;

let KD2_CHECK = prove
 (KD2_CHECK_STMT,
  REPEAT STRIP_TAC THEN REWRITE_TAC[mlkem512; mlkem_decaps_check] THEN
  CONV_TAC NUM_REDUCE_CONV THEN ASM_REWRITE_TAC[mlkem_h] THEN
  CONV_TAC(LAND_CONV SYM_CONV) THEN CONV_TAC SYM_CONV THEN
  MATCH_MP_TAC NUM_OF_BYTELIST_INJ THEN
  REWRITE_TAC[mlkem_slice; LENGTH_LIST_OF_SEQ; LENGTH_SHA3_256]);;

let KD2_BUFFER_ADDRESS = prove
 (KD2_BUFFER_ADDRESS_STMT,
  REWRITE_TAC[REJ_ALIGNED_16_32] THEN GEN_TAC THEN
  COND_CASES_TAC THEN POP_ASSUM MP_TAC THEN
  W(fun (_,w) -> ACCEPT_TAC(BITBLAST_RULE w)));;

let KD2_TEST = prove
 (KD2_TEST_STMT,
  REPEAT STRIP_TAC THEN
  REWRITE_TAC[GSYM WORD_ADD_ASSOC; GSYM WORD_ADD;
              WORD_RULE `word_sub (word_add a x) (word_add a y):int64 =
                         word_sub x y`] THEN
  REWRITE_TAC[VAL_EQ_0; WORD_SUB_EQ_0; GSYM VAL_EQ; VAL_WORD; DIMINDEX_64] THEN
  SUBGOAL_THEN `b + 768 < 2 EXP 64 /\ (b + 16 * i) + 16 < 2 EXP 64`
   (fun th -> SIMP_TAC[th; MOD_LT]) THENL
   [CONV_TAC NUM_REDUCE_CONV THEN ASM_ARITH_TAC; ASM_ARITH_TAC]);;

let MLKEM_NATIVE_DEC_K2_GCC12_O3_IMAGE_SUBROUTINE_CORRECT = prove
 (MLKEM_NATIVE_DEC_K2_GCC12_O3_IMAGE_SUBROUTINE_CORRECT_STMT,
  KD2_INTRO_TAC THEN ASM_CASES_TAC `aligned 32 (stackpointer:int64)` THENL
   [KD2_CASE_TAC 12064; KD2_CASE_TAC 12080]);;

let KD2_KBAR_ADDR = prove
 (KD2_KBAR_ADDR_STMT,
  REPEAT GEN_TAC THEN REWRITE_TAC[WORD_ADD; GSYM WORD_ADD_ASSOC] THEN
  CONV_TAC(ONCE_DEPTH_CONV WORD_REDUCE_CONV) THEN REWRITE_TAC[WORD_ADD_0]);;

let MLKEM_NATIVE_DEC_K2_GCC12_O3_IMAGE_SUBROUTINE_SAFE = prove
 (MLKEM_NATIVE_DEC_K2_GCC12_O3_IMAGE_SUBROUTINE_SAFE_STMT,
  KD2_SAFE_INTRO_TAC THEN
  ASM_CASES_TAC
   `num_of_bytelist(hh:byte list) = num_of_bytelist(sha3_256 ekk)` THEN
  ASM_REWRITE_TAC[] THENL
   [ENSURES_EVENTS_WHILE_UP2_TAC `48` `pc + mlkem512_dec_loop1`
    `pc + mlkem512_dec_loop1_exit`
     KD2_SAFE_INV THEN
    REPEAT CONJ_TAC THENL
     [ARITH_TAC; KD2_SAFE_PART1_TAC; KD2_SAFE_BODY_TAC;
      ENSURES_EVENTS_WHILE_UP2_TAC `32` `pc + mlkem512_dec_loop2`
       `pc + mlkem512_dec_loop2_exit`
       KD2_SAFE_CMOV_INV THEN
      REPEAT CONJ_TAC THENL
       [ARITH_TAC; KD2_SAFE_EXIT_A_TAC; KD2_SAFE_CMOV_BODY_TAC;
        KD2_SAFE_EXIT_B_TAC]];
    KD2_SAFE_BAD_TAC]);;
