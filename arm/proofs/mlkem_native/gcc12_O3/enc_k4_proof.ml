needs "arm/proofs/mlkem_native/gcc12_O3/enc_k4_spec.ml";;


let KER4_BUFFER_ADDRESS = prove
 (KER4_BUFFER_ADDRESS_STMT,
  REWRITE_TAC[REJ_ALIGNED_16_32] THEN GEN_TAC THEN
  COND_CASES_TAC THEN POP_ASSUM MP_TAC THEN
  W(fun (_,w) -> ACCEPT_TAC(BITBLAST_RULE w)));;

let MLKEM_NATIVE_ENC_K4_GCC12_O3_IMAGE_SUBROUTINE_CORRECT = prove
 (MLKEM_NATIVE_ENC_K4_GCC12_O3_IMAGE_SUBROUTINE_CORRECT_STMT,
  KER4_INTRO_TAC THEN ASM_CASES_TAC `aligned 32 (stackpointer:int64)` THENL
   [KER4_CASE_TAC 23104; KER4_CASE_TAC 23120]);;

let MLKEM_NATIVE_ENC_K4_GCC12_O3_IMAGE_SUBROUTINE_SAFE = prove
 (MLKEM_NATIVE_ENC_K4_GCC12_O3_IMAGE_SUBROUTINE_SAFE_STMT,
  KER4_SAFE_INTRO_TAC THEN
  ASM_CASES_TAC `aligned 32 (stackpointer:int64)` THENL
   [KER4_SAFE_CASE_TAC 23104; KER4_SAFE_CASE_TAC 23120]);;
