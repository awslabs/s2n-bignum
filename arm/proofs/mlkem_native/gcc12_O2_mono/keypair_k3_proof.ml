needs "arm/proofs/mlkem_native/gcc12_O2_mono/keypair_k3_spec.ml";;


let KR3_BUFFER_ADDRESS = prove
 (KR3_BUFFER_ADDRESS_STMT,
  REWRITE_TAC[REJ_ALIGNED_16_32] THEN GEN_TAC THEN
  COND_CASES_TAC THEN POP_ASSUM MP_TAC THEN
  W(fun (_,w) -> ACCEPT_TAC(BITBLAST_RULE w)));;

let MLKEM_NATIVE_KEYPAIR_K3_GCC12_O2_MONO_IMAGE_SUBROUTINE_CORRECT = prove
 (MLKEM_NATIVE_KEYPAIR_K3_GCC12_O2_MONO_IMAGE_SUBROUTINE_CORRECT_STMT,
  KR3_INTRO_TAC THEN ASM_CASES_TAC `aligned 32 (stackpointer:int64)` THENL
   [KR3_CASE_TAC 14784; KR3_CASE_TAC 14768]);;

let KEM_BYTELIST_32 = prove
 (KEM_BYTELIST_32_STMT,
  MESON_TAC[BYTELIST_OF_NUM_OF_BYTELIST]);;

let MLKEM_NATIVE_KEYPAIR_K3_GCC12_O2_MONO_IMAGE_SUBROUTINE_SAFE = prove
 (MLKEM_NATIVE_KEYPAIR_K3_GCC12_O2_MONO_IMAGE_SUBROUTINE_SAFE_STMT,
  KR3_SAFE_INTRO_TAC THEN
  ASM_CASES_TAC `aligned 32 (stackpointer:int64)` THENL
   [KR3_SAFE_CASE_TAC 14784; KR3_SAFE_CASE_TAC 14768]);;
