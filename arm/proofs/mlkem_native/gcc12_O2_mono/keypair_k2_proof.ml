needs "arm/proofs/mlkem_native/gcc12_O2_mono/keypair_k2_spec.ml";;


let KR2_BUFFER_ADDRESS = prove
 (KR2_BUFFER_ADDRESS_STMT,
  REWRITE_TAC[REJ_ALIGNED_16_32] THEN GEN_TAC THEN
  COND_CASES_TAC THEN POP_ASSUM MP_TAC THEN
  W(fun (_,w) -> ACCEPT_TAC(BITBLAST_RULE w)));;

let MLKEM_NATIVE_KEYPAIR_K2_GCC12_O2_MONO_IMAGE_SUBROUTINE_CORRECT = prove
 (MLKEM_NATIVE_KEYPAIR_K2_GCC12_O2_MONO_IMAGE_SUBROUTINE_CORRECT_STMT,
  KR2_INTRO_TAC THEN ASM_CASES_TAC `aligned 32 (stackpointer:int64)` THENL
   [KR2_CASE_TAC 9632; KR2_CASE_TAC 9616]);;

let KEM_BYTELIST_32 = prove
 (KEM_BYTELIST_32_STMT,
  MESON_TAC[BYTELIST_OF_NUM_OF_BYTELIST]);;

let MLKEM_NATIVE_KEYPAIR_K2_GCC12_O2_MONO_IMAGE_SUBROUTINE_SAFE = prove
 (MLKEM_NATIVE_KEYPAIR_K2_GCC12_O2_MONO_IMAGE_SUBROUTINE_SAFE_STMT,
  KR2_SAFE_INTRO_TAC THEN
  ASM_CASES_TAC `aligned 32 (stackpointer:int64)` THENL
   [KR2_SAFE_CASE_TAC 9632; KR2_SAFE_CASE_TAC 9616]);;
