needs "arm/proofs/mlkem_native/clang17_O2/enc_k2_spec.ml";;


let KER2_BUFFER_ADDRESS = prove
 (KER2_BUFFER_ADDRESS_STMT,
  REWRITE_TAC[REJ_ALIGNED_16_32] THEN GEN_TAC THEN
  COND_CASES_TAC THEN POP_ASSUM MP_TAC THEN
  W(fun (_,w) -> ACCEPT_TAC(BITBLAST_RULE w)));;

let MLKEM_NATIVE_ENC_K2_CLANG17_O2_IMAGE_SUBROUTINE_CORRECT = prove
 (MLKEM_NATIVE_ENC_K2_CLANG17_O2_IMAGE_SUBROUTINE_CORRECT_STMT,
  KER2_INTRO_TAC THEN PAR_THENL (ASM_CASES_TAC `aligned 32 (stackpointer:int64)`)
   [KER2_CASE_TAC 13728; KER2_CASE_TAC 13744]);;

let MLKEM_NATIVE_ENC_K2_CLANG17_O2_IMAGE_SUBROUTINE_SAFE = prove
 (MLKEM_NATIVE_ENC_K2_CLANG17_O2_IMAGE_SUBROUTINE_SAFE_STMT,
  KER2_SAFE_INTRO_TAC THEN
  PAR_THENL (ASM_CASES_TAC `aligned 32 (stackpointer:int64)`)
   [KER2_SAFE_CASE_TAC 13728; KER2_SAFE_CASE_TAC 13744]);;
