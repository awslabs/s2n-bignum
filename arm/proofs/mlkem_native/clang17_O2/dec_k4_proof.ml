let KPKE_ENCRYPT_LENGTH_1024 = prove
 (KPKE_ENCRYPT_LENGTH_1024_STMT,
  REWRITE_TAC[mlkem1024; KPKE_ENCRYPT_LENGTH] THEN CONV_TAC NUM_REDUCE_CONV);;

let KPKE_DECRYPT_LENGTH_1024 = prove
 (KPKE_DECRYPT_LENGTH_1024_STMT,
  REWRITE_TAC[mlkem1024; KPKE_DECRYPT_LENGTH]);;

let KD4_TEST = prove
 (KD4_TEST_STMT,
  CONV_TAC EXPAND_CASES_CONV THEN
  CONV_TAC(DEPTH_CONV(WORD_RED_CONV ORELSEC NUM_RED_CONV)) THEN
  REWRITE_TAC[]);;

let KD4_CHECK = prove
 (KD4_CHECK_STMT,
  REPEAT STRIP_TAC THEN REWRITE_TAC[mlkem1024; mlkem_decaps_check] THEN
  CONV_TAC NUM_REDUCE_CONV THEN ASM_REWRITE_TAC[mlkem_h] THEN
  CONV_TAC(LAND_CONV SYM_CONV) THEN CONV_TAC SYM_CONV THEN
  MATCH_MP_TAC NUM_OF_BYTELIST_INJ THEN
  REWRITE_TAC[mlkem_slice; LENGTH_LIST_OF_SEQ; LENGTH_SHA3_256]);;

let KD4_BUFFER_ADDRESS = prove
 (KD4_BUFFER_ADDRESS_STMT,
  REWRITE_TAC[REJ_ALIGNED_16_32] THEN GEN_TAC THEN
  COND_CASES_TAC THEN POP_ASSUM MP_TAC THEN
  W(fun (_,w) -> ACCEPT_TAC(BITBLAST_RULE w)));;

let KD4_EQ_LEMMA = prove
 (KD4_EQ_STMT,
  REPEAT STRIP_TAC THEN
  REWRITE_TAC[GSYM VAL_EQ; VAL_WORD; DIMINDEX_128; MOD_MOD_REFL] THEN
  SUBGOAL_THEN `n DIV 2 EXP 128 < 2 EXP 128 /\ h DIV 2 EXP 128 < 2 EXP 128`
   (fun th -> SIMP_TAC[th; MOD_LT]) THENL
   [ASM_SIMP_TAC[RDIV_LT_EQ; EXP_EQ_0; ARITH_EQ; GSYM EXP_ADD;
                 ARITH_RULE `128 + 128 = 256`];
    ALL_TAC] THEN
  EQ_TAC THENL [SIMP_TAC[]; ALL_TAC] THEN
  MESON_TAC[DIVISION_SIMP]);;

let KD4_CMOV_TEST = prove
 (KD4_CMOV_TEST_STMT,
  REPEAT STRIP_TAC THEN
  REWRITE_TAC[VAL_WORD_ADD; VAL_WORD; DIMINDEX_64] THEN
  CONV_TAC NUM_REDUCE_CONV THEN
  SUBGOAL_THEN `i MOD 18446744073709551616 = i` SUBST1_TAC THENL
   [MATCH_MP_TAC MOD_LT THEN ASM_ARITH_TAC; ALL_TAC] THEN
  ASM_CASES_TAC `i + 1 < 32` THEN ASM_REWRITE_TAC[] THENL
   [MATCH_MP_TAC(ARITH_RULE `~(x = 0) /\ x MOD n = x ==> ~(x MOD n = 0)`) THEN
    CONJ_TAC THENL [ARITH_TAC; MATCH_MP_TAC MOD_LT THEN ASM_ARITH_TAC];
    SUBGOAL_THEN `i = 31` SUBST1_TAC THENL [ASM_ARITH_TAC; ALL_TAC] THEN
    CONV_TAC NUM_REDUCE_CONV]);;

let KD4_BYTES256 = prove
 (KD4_BYTES256_STMT,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  MP_TAC(SPECL [`a:int64`; `l:num`; `2 * i`; `n:num`; `s:armstate`]
               KEM_BYTES128) THEN
  MP_TAC(SPECL [`a:int64`; `l:num`; `2 * i + 1`; `n:num`; `s:armstate`]
               KEM_BYTES128) THEN
  ASM_REWRITE_TAC[] THEN
  REWRITE_TAC[ARITH_RULE `16 * (2 * i) = 32 * i`;
              ARITH_RULE `128 * (2 * i) = 256 * i`;
              ARITH_RULE `16 * (2 * i + 1) = 32 * i + 16`;
              ARITH_RULE `128 * (2 * i + 1) = 256 * i + 128`] THEN
  ANTS_TAC THENL [ASM_ARITH_TAC; ALL_TAC] THEN DISCH_TAC THEN
  ANTS_TAC THENL [ASM_ARITH_TAC; ALL_TAC] THEN DISCH_TAC THEN
  ASM_REWRITE_TAC[]);;

let KD4_OR_STEP = prove
 (KD4_OR_STEP_STMT,
  REPEAT GEN_TAC THEN REWRITE_TAC[WORD_OR_EQ_0; WORD_XOR_EQ_0] THEN
  REWRITE_TAC[GSYM VAL_EQ; VAL_WORD; DIMINDEX_128] THEN
  CONV_TAC NUM_REDUCE_CONV THEN REWRITE_TAC[MOD_MOD_REFL] THEN
  REWRITE_TAC[VAL_EQ; CONJ_ACI; EQ_SYM_EQ]);;

let KD4_MOD_STEP = prove
 (KD4_MOD_STEP_STMT,
  REPEAT GEN_TAC THEN
  REWRITE_TAC[ARITH_RULE `256 * (i + 1) = 128 * ((2 * i + 1) + 1)`] THEN
  REWRITE_TAC[KEM_MOD_STEP] THEN
  REWRITE_TAC[ARITH_RULE `128 * (2 * i + 1) = 128 * ((2 * i) + 1)`] THEN
  REWRITE_TAC[KEM_MOD_STEP] THEN
  REWRITE_TAC[ARITH_RULE `128 * (2 * i) = 256 * i`;
              ARITH_RULE `128 * ((2 * i) + 1) = 256 * i + 128`] THEN
  REWRITE_TAC[CONJ_ACI]);;

