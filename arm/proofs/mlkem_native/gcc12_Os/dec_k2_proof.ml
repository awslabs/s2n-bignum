needs "arm/proofs/mlkem_native/gcc12_Os/dec_k2_spec.ml";;


let KPKE_ENCRYPT_LENGTH_512 = prove
 (KPKE_ENCRYPT_LENGTH_512_STMT,
  REWRITE_TAC[mlkem512; KPKE_ENCRYPT_LENGTH] THEN CONV_TAC NUM_REDUCE_CONV);;

let KPKE_DECRYPT_LENGTH_512 = prove
 (KPKE_DECRYPT_LENGTH_512_STMT,
  REWRITE_TAC[mlkem512; KPKE_DECRYPT_LENGTH]);;

let KD2_CHECK = prove
 (KD2_CHECK_STMT,
  REPEAT STRIP_TAC THEN REWRITE_TAC[mlkem512; mlkem_decaps_check] THEN
  CONV_TAC NUM_REDUCE_CONV THEN ASM_REWRITE_TAC[mlkem_h] THEN
  CONV_TAC(LAND_CONV SYM_CONV) THEN CONV_TAC SYM_CONV THEN
  MATCH_MP_TAC NUM_OF_BYTELIST_INJ THEN
  REWRITE_TAC[mlkem_slice; LENGTH_LIST_OF_SEQ; LENGTH_SHA3_256]);;

let KD2_BUFFER_ADDRESS = prove
 (KD2_BUFFER_ADDRESS_STMT,
  REWRITE_TAC[REJ_ALIGNED_16_32] THEN GEN_TAC THEN
  COND_CASES_TAC THEN POP_ASSUM MP_TAC THEN
  W(fun (_,w) -> ACCEPT_TAC(BITBLAST_RULE w)));;

let KD2_CMOV_TEST = prove
 (KD2_CMOV_TEST_STMT,
  REPEAT STRIP_TAC THEN REWRITE_TAC[VAL_WORD; DIMINDEX_64] THEN
  CONV_TAC NUM_REDUCE_CONV THEN
  ASM_CASES_TAC `i + 1 < 32` THEN ASM_REWRITE_TAC[] THENL
   [SUBGOAL_THEN
     `(i + 18446744073709551585) MOD 18446744073709551616 =
      i + 18446744073709551585`
    SUBST1_TAC THENL [MATCH_MP_TAC MOD_LT THEN ASM_ARITH_TAC; ALL_TAC] THEN
    ARITH_TAC;
    SUBGOAL_THEN `i = 31` SUBST1_TAC THENL [ASM_ARITH_TAC; ALL_TAC] THEN
    CONV_TAC NUM_REDUCE_CONV]);;

let MLKEM_NATIVE_DEC_K2_GCC12_OS_IMAGE_SUBROUTINE_CORRECT = prove
 (MLKEM_NATIVE_DEC_K2_GCC12_OS_IMAGE_SUBROUTINE_CORRECT_STMT,
  KD2_INTRO_TAC THEN PAR_THENL (ASM_CASES_TAC `aligned 32 (stackpointer:int64)`)
   [KD2_CASE_TAC 12128; KD2_CASE_TAC 12112]);;

let MLKEM_NATIVE_DEC_K2_GCC12_OS_IMAGE_SUBROUTINE_SAFE = prove
 (MLKEM_NATIVE_DEC_K2_GCC12_OS_IMAGE_SUBROUTINE_SAFE_STMT,
  KD2_SAFE_INTRO_TAC THEN
  ASM_CASES_TAC
   `num_of_bytelist(hh:byte list) = num_of_bytelist(sha3_256 ekk)` THEN
  ASM_REWRITE_TAC[] THENL [KD2_SAFE_OK_TAC; KD2_SAFE_BAD_TAC]);;
