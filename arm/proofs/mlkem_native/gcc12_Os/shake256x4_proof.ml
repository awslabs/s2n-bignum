let SHAKE256X4_ALIGNED_16_32 = prove
 (SHAKE256X4_ALIGNED_16_32_STMT,
  CONJ_TAC THEN GEN_TAC THEN REWRITE_TAC[aligned; DIMINDEX_64] THEN
  CONV_TAC NUM_REDUCE_CONV THEN
  CONV_TAC(ONCE_DEPTH_CONV DIVIDES_CONV) THEN REWRITE_TAC[] THENL
   [MP_TAC(ISPECL [`x:int64`; `4`] (CONJUNCT1 WORD_AND_MASK_WORD));
    MP_TAC(ISPECL [`x:int64`; `5`] (CONJUNCT1 WORD_AND_MASK_WORD))] THEN
  CONV_TAC(ONCE_DEPTH_CONV NUM_REDUCE_CONV) THEN DISCH_THEN SUBST1_TAC THEN
  REWRITE_TAC[DIVIDES_MOD; GSYM VAL_EQ_0; VAL_WORD; DIMINDEX_64] THEN
  SIMP_TAC[MOD_LT; ARITH_RULE `x MOD 16 < 16`; ARITH_RULE `x MOD 32 < 32`;
           ARITH_RULE `x < 16 ==> x < 2 EXP 64`;
           ARITH_RULE `x < 32 ==> x < 2 EXP 64`]);;

let SHAKE256X4_CTX_ADDRESS = prove
 (SHAKE256X4_CTX_ADDRESS_STMT,
  REWRITE_TAC[SHAKE256X4_ALIGNED_16_32] THEN GEN_TAC THEN
  COND_CASES_TAC THEN POP_ASSUM MP_TAC THEN
  W(fun (_,w) -> ACCEPT_TAC(BITBLAST_RULE w)));;

let SHAKE256X4_MUL136 = prove
 (SHAKE256X4_MUL136_STMT,
  GEN_TAC THEN REWRITE_TAC[ADD_CLAUSES; VAL_WORD; DIMINDEX_64; WORD_EQ;
                           CONG] THEN
  CONV_TAC MOD_DOWN_CONV THEN AP_THM_TAC THEN AP_TERM_TAC THEN ARITH_TAC);;

let SHAKE256X4_VAL136 = prove
 (SHAKE256X4_VAL136_STMT,
  MATCH_MP_TAC VAL_WORD_EQ THEN REWRITE_TAC[DIMINDEX_64] THEN
  CONV_TAC NUM_REDUCE_CONV);;

let SHAKE256X4_SPONGE = prove
 (SHAKE256X4_SPONGE_STMT,
  REPEAT STRIP_TAC THEN REWRITE_TAC[shake256] THEN
  MATCH_MP_TAC KECCAK_SPONGE_BLOCK THEN ASM_REWRITE_TAC[] THEN
  CONV_TAC NUM_REDUCE_CONV);;

let SHAKE256X4_TMP_LEMMA = prove
 (SHAKE256X4_TMP_LEMMA_STMT,
  REPEAT GEN_TAC THEN
  REWRITE_TAC[READ_COMPONENT_COMPOSE] THEN STRIP_TAC THEN
  MP_TAC(ISPECL [`a:int64`; `136`; `n:num`; `read memory s`]
                READ_BYTES_MOD) THEN
  ASM_REWRITE_TAC[MOD_MOD_EXP_MIN] THEN
  ASM_SIMP_TAC[ARITH_RULE
   `n <= 136 ==> MIN 136 n = n /\ MIN (8 * 136) (8 * n) = 8 * n`]);;

let SHAKE256X4_NSUM_ONE = prove
 (SHAKE256X4_NSUM_ONE_STMT,
  GEN_TAC THEN REWRITE_TAC[num_CONV `1`; NSUM_CLAUSES_NUMSEG_LT] THEN
  REWRITE_TAC[NSUM_CLAUSES_NUMSEG_LT; MULT_CLAUSES; EXP; ADD_CLAUSES;
              keccak_squeeze] THEN
  REWRITE_TAC[num_CONV `1`; keccak_squeeze] THEN
  REWRITE_TAC[MULT_CLAUSES; EXP; ADD_CLAUSES]);;

let SHAKE256X4_NSUM = prove
 (SHAKE256X4_NSUM_STMT,
  REPEAT GEN_TAC THEN DISCH_TAC THEN SPEC_TAC(`nb:num`,`nb:num`) THEN
  INDUCT_TAC THENL
   [REWRITE_TAC[NSUM_CLAUSES_NUMSEG_LT; MULT_CLAUSES; list_of_seq;
                num_of_bytelist];
    REWRITE_TAC[NSUM_CLAUSES_NUMSEG_LT] THEN ASM_REWRITE_TAC[] THEN
    REWRITE_TAC[ARITH_RULE `136 * SUC nb = 136 * nb + 136`;
                NUM_OF_BYTELIST_LIST_OF_SEQ_ADD] THEN
    FIRST_X_ASSUM(MP_TAC o SPECL [`nb:num`; `136`]) THEN
    REWRITE_TAC[LE_REFL] THEN DISCH_THEN SUBST1_TAC THEN
    REWRITE_TAC[ADD1; MULT_ASSOC]]);;

let MLKEM_NATIVE_SHAKE256X4_GCC12_OS_IMAGE_SUBROUTINE_CORRECT = prove
 (MLKEM_NATIVE_SHAKE256X4_GCC12_OS_IMAGE_SUBROUTINE_CORRECT_STMT,
  MAP_EVERY X_GEN_TAC
   [`out0:int64`; `out1:int64`; `out2:int64`; `out3:int64`; `outlen:num`;
    `in0:int64`; `in1:int64`; `in2:int64`; `in3:int64`; `inlen:num`;
    `inp0:byte list`; `inp1:byte list`; `inp2:byte list`; `inp3:byte list`;
    `guard:int64`; `mf:int64`; `mc:int64`; `ea:int64`; `el:num`; `ev:num`;
    `pc:num`] THEN
  WORD_FORALL_OFFSET_TAC 1824 THEN
  MAP_EVERY X_GEN_TAC [`stackpointer:int64`; `returnaddress:int64`] THEN
  REWRITE_TAC[MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI; C_ARGUMENTS;
              ALL; ALLPAIRS; PAIRWISE; NONOVERLAPPING_CLAUSES] THEN
  DISCH_THEN(CONJUNCTS_THEN2
   (fun th -> ASSUME_TAC th THEN
              LABEL_TAC "H_MEMSET" (REWRITE_RULE[memset_contract] th))
   (CONJUNCTS_THEN2
    (LABEL_TAC "H_MEMCPY" o REWRITE_RULE[memcpy_contract])
    (REPEAT_TCL CONJUNCTS_THEN ASSUME_TAC))) THEN
  SHAKE256X4_SETUP_TAC THEN SHAKE256X4_BOUND_TAC THEN
  SHAKE256X4_ABSORBED_TAC THEN

  (*** Zeroing the context with memset, and the absorption ***)

  ENSURES_SEQUENCE_TAC
   `pc + mlkem_shake256x4_after_mlk_keccak_absorb_once_x4` SHAKE256X4_A1 THEN
  CONJ_TAC THENL
   [ENSURES_INIT_TAC "s0" THEN
    ARM_STEPS_TAC MLKEM_NATIVE_SHAKE256X4_GCC12_OS_EXEC (1--5) THEN
    MLKEM_NATIVE_ADRP_TAC THEN
    ARM_STEPS_TAC MLKEM_NATIVE_SHAKE256X4_GCC12_OS_EXEC (6--13) THEN
    SHAKE256X4_CTX_TAC THEN
    ARM_STEPS_TAC MLKEM_NATIVE_SHAKE256X4_GCC12_OS_EXEC (14--27) THEN
    LIBC_PLT_TAC MLKEM_NATIVE_SHAKE256X4_GCC12_OS_EXEC 27 THEN
    LIBC_CALL_TAC "H_MEMSET" MLKEM_NATIVE_SHAKE256X4_GCC12_OS_EXEC
     [`read X0 s`; `read X1 s`; `read X2 s`; `read X30 s`] 32 THEN
    MEMSET_ZERO_BYTES_TAC THEN
    ARM_STEPS_TAC MLKEM_NATIVE_SHAKE256X4_GCC12_OS_EXEC (33--40) THEN
    SHAKE256X4_NBLOCKS_TAC THEN SHAKE256X4_GOT_TAC THEN
    LOCAL_ABSORB_X4_TAC
     [`read X0 s`; `136`; `read X2 s`; `read X3 s`; `read X4 s`;
      `read X5 s`; `inlen:num`; `num_of_bytelist(inp0:byte list)`;
      `num_of_bytelist(inp1:byte list)`; `num_of_bytelist(inp2:byte list)`;
      `num_of_bytelist(inp3:byte list)`; `guard:int64`; `pc:num`;
      `read SP s`; `read X30 s`] 41 THEN
    RULE_ASSUM_TAC(REWRITE_RULE[READ_MEMORY_WBYTES_1600]) THEN
    ENSURES_FINAL_STATE_TAC THEN ASM_REWRITE_TAC[];
    ALL_TAC] THEN

  (*** The whole blocks ***)

  ENSURES_SEQUENCE_TAC
   `pc + mlkem_shake256x4_after_mlk_keccak_squeezeblocks_x4_1`
   SHAKE256X4_A2 THEN
  CONJ_TAC THENL
   [ENSURES_INIT_TAC "s0" THEN
    SUBGOAL_THEN `136 * nb <= outlen` ASSUME_TAC THENL
     [MAP_EVERY UNDISCH_TAC [`136 * nb + rest = outlen`] THEN ARITH_TAC;
      ALL_TAC] THEN
    ARM_STEPS_TAC MLKEM_NATIVE_SHAKE256X4_GCC12_OS_EXEC (1--11) THEN
    RULE_ASSUM_TAC(REWRITE_RULE[SHAKE256X4_MUL136]) THEN
    SHAKE256X4_STATES_TAC THEN
    LOCAL_SQUEEZE_X4_TAC
     [`read X0 s`; `read X1 s`; `read X2 s`; `read X3 s`; `nb:num`;
      `read X5 s`; `136`; `S0:1600 word`; `S1:1600 word`; `S2:1600 word`;
      `S3:1600 word`; `pc:num`; `read SP s`; `read X30 s`] 12 THEN
    RULE_ASSUM_TAC(REWRITE_RULE[READ_MEMORY_WBYTES_1600]) THEN
    MAP_EVERY (fun (inp,sv) ->
      FIRST_ASSUM(fun th ->
        let th' = MP (SPECL [inp; sv; `nb:num`] SHAKE256X4_NSUM) th in
        RULE_ASSUM_TAC(REWRITE_RULE[th'])))
     (zip [`inp0:byte list`; `inp1:byte list`; `inp2:byte list`;
           `inp3:byte list`]
          [`S0:1600 word`; `S1:1600 word`; `S2:1600 word`;
           `S3:1600 word`]) THEN
    ENSURES_FINAL_STATE_TAC THEN ASM_REWRITE_TAC[];
    ALL_TAC] THEN

  (*** The remaining bytes, if any, through the buffers on the stack ***)

  ENSURES_SEQUENCE_TAC
   `pc + mlkem_shake256x4_join1` SHAKE256X4_A3 THEN
  CONJ_TAC THENL
   [ASM_CASES_TAC `rest = 0` THEN
    ENSURES_INIT_TAC "s0" THEN
    ARM_STEPS_TAC MLKEM_NATIVE_SHAKE256X4_GCC12_OS_EXEC (1--2) THEN
    SHAKE256X4_NBLOCKS_TAC THEN
    SHAKE256X4_REST_TAC THEN
    ARM_STEPS_TAC MLKEM_NATIVE_SHAKE256X4_GCC12_OS_EXEC (3--3) THENL
     [SHAKE256X4_BRANCH_TAC TRUTH `rest = 0` THEN
      ENSURES_FINAL_STATE_TAC THEN ASM_REWRITE_TAC[] THEN
      SUBGOAL_THEN `outlen = 136 * nb` SUBST1_TAC THENL
       [MAP_EVERY UNDISCH_TAC [`rest = 0`; `136 * nb + rest = outlen`] THEN
        ARITH_TAC;
        ASM_REWRITE_TAC[]];
      ALL_TAC] THEN

    (*** Otherwise one more block into the buffers, and the memcpys ***)

    SHAKE256X4_BRANCH_TAC TRUTH `~(rest = 0)` THEN
    ARM_STEPS_TAC MLKEM_NATIVE_SHAKE256X4_GCC12_OS_EXEC (4--11) THEN
    SHAKE256X4_STATES_TAC THEN
    LOCAL_SQUEEZE_X4_TAC
     [`read X0 s`; `read X1 s`; `read X2 s`; `read X3 s`; `1`;
      `read X5 s`; `136`; `keccak_squeeze nb (S0:1600 word)`;
      `keccak_squeeze nb (S1:1600 word)`; `keccak_squeeze nb (S2:1600 word)`;
      `keccak_squeeze nb (S3:1600 word)`; `pc:num`; `read SP s`;
      `read X30 s`] 12 THEN
    RULE_ASSUM_TAC(REWRITE_RULE[READ_MEMORY_WBYTES_1600; MULT_CLAUSES;
                                SHAKE256X4_NSUM_ONE]) THEN
    MAP_EVERY (fun (a,sv,k0,k) ->
      SHAKE256X4_TMP_TAC a THEN
      ARM_STEPS_TAC MLKEM_NATIVE_SHAKE256X4_GCC12_OS_EXEC (k0--k) THEN
      LIBC_PLT_TAC MLKEM_NATIVE_SHAKE256X4_GCC12_OS_EXEC k THEN
      LIBC_CALL_TAC "H_MEMCPY" MLKEM_NATIVE_SHAKE256X4_GCC12_OS_EXEC
       [`read X0 s`; `read X1 s`; `read X2 s`;
        vsubst [sv,`S:1600 word`]
         `val(keccak_f1600(keccak_squeeze nb (S:1600 word))) MOD
          2 EXP (8 * rest)`;
        `read X30 s`] (k + 5))
     [`word_add (stackpointer:int64) (word 1272)`,`S0:1600 word`,13,16;
      `word_add (stackpointer:int64) (word 1408)`,`S1:1600 word`,22,25;
      `word_add (stackpointer:int64) (word 1544)`,`S2:1600 word`,31,35;
      `word_add (stackpointer:int64) (word 1680)`,`S3:1600 word`,41,45] THEN
    ENSURES_FINAL_STATE_TAC THEN ASM_REWRITE_TAC[] THEN
    SUBGOAL_THEN `outlen = 136 * nb + rest` SUBST1_TAC THENL
     [ASM_REWRITE_TAC[]; ALL_TAC] THEN
    REPEAT CONJ_TAC THEN
    REWRITE_TAC[READ_COMPONENT_COMPOSE; READ_BYTES_COMBINE;
                NUM_OF_BYTELIST_LIST_OF_SEQ_ADD] THEN
    REWRITE_TAC[GSYM READ_COMPONENT_COMPOSE] THEN ASM_REWRITE_TAC[] THEN
    AP_TERM_TAC THEN AP_TERM_TAC THEN ASM_SIMP_TAC[] THEN
    REWRITE_TAC[GSYM ADD1; keccak_squeeze];
    ALL_TAC] THEN

  (*** Zeroing the context and the buffers, the stack guard, the return ***)

  ENSURES_INIT_TAC "s0" THEN
  ARM_STEPS_TAC MLKEM_NATIVE_SHAKE256X4_GCC12_OS_EXEC (1--3) THEN
  SHAKE256X4_GOT_AT_TAC 131048 THEN
  LOCAL_ZEROIZE_TAC
   [`read X0 s`; `800`; `mf:int64`; `ea:int64`; `el:num`; `ev:num`;
    `pc:num`; `read SP s`; `read X30 s`] 4 THEN
  MAP_EVERY (fun (k0,k) ->
    ARM_STEPS_TAC MLKEM_NATIVE_SHAKE256X4_GCC12_OS_EXEC (k0--k) THEN
    SHAKE256X4_GOT_AT_TAC 131048 THEN
    LOCAL_ZEROIZE_TAC
     [`read X0 s`; `136`; `mf:int64`; `ea:int64`; `el:num`; `ev:num`;
      `pc:num`; `read SP s`; `read X30 s`] (k + 1))
   [5,7; 9,11; 13,15; 17,19] THEN
  ARM_STEPS_TAC MLKEM_NATIVE_SHAKE256X4_GCC12_OS_EXEC (21--21) THEN
  MLKEM_NATIVE_ADRP_TAC THEN
  ARM_STEPS_TAC MLKEM_NATIVE_SHAKE256X4_GCC12_OS_EXEC (22--35) THEN
  ENSURES_FINAL_STATE_TAC THEN ASM_REWRITE_TAC[]);;

let MLKEM_NATIVE_SHAKE256X4_GCC12_OS_IMAGE_SUBROUTINE_SAFE = time prove
 (MLKEM_NATIVE_SHAKE256X4_GCC12_OS_IMAGE_SUBROUTINE_SAFE_STMT,
  REPEAT GEN_TAC THEN DISCH_TAC THEN
  FIRST_ASSUM(fun th ->
    ASSUME_CALLEE_SAFETY_TAILED_TAC
     (REWRITE_RULE[memset_safety_contract] (CONJUNCT1 th)) "H_MEMSET") THEN
  FIRST_ASSUM(fun th ->
    ASSUME_CALLEE_SAFETY_TAILED_TAC
     (REWRITE_RULE[memcpy_safety_contract] (CONJUNCT2 th)) "H_MEMCPY") THEN
  FIRST_ASSUM(fun th ->
    ASSUME_CALLEE_SAFETY_TAILED_TAC
     (MATCH_MP MLKEM_NATIVE_ZEROIZE_3_GCC12_OS_IMAGE_SUBROUTINE_SAFE
               (CONJUNCT1 th))
     "H_ZEROIZE") THEN
  ASSUME_CALLEE_SAFETY_TAILED_TAC
    MLKEM_NATIVE_KECCAK_ABSORB_ONCE_X4_GCC12_OS_IMAGE_SUBROUTINE_SAFE
    "H_ABSORB" THEN
  ASSUME_CALLEE_SAFETY_TAILED_TAC
    MLKEM_NATIVE_KECCAK_SQUEEZEBLOCKS_X4_GCC12_OS_IMAGE_SUBROUTINE_SAFE
    "H_SQUEEZE" THEN
  CONCRETIZE_F_EVENTS_TAC SHAKE256X4_F_EVENTS THEN
  REPEAT META_EXISTS_TAC THEN STRIP_TAC THEN
  REPEAT_GEN_AND_OFFSET_STACKPTR_TAC THEN
  REWRITE_TAC[MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI; C_ARGUMENTS;
              ALL; ALLPAIRS; PAIRWISE; NONOVERLAPPING_CLAUSES;
              fst MLKEM_NATIVE_SHAKE256X4_GCC12_OS_EXEC] THEN
  DISCH_THEN(REPEAT_TCL CONJUNCTS_THEN ASSUME_TAC) THEN
  SHAKE256X4_SETUP_TAC THEN SHAKE256X4_BOUND_TAC THEN
  ENSURES_EVENTS_SEQUENCE_TAC `pc + mlkem_shake256x4_join1`
   (SHAKE256X4_PUBLIC SHAKE256X4_A3) THEN
  CONJ_TAC THENL [ALL_TAC; SHAKE256X4_SAFE_END_TAC] THEN
  ENSURES_EVENTS_SEQUENCE_TAC
   `pc + mlkem_shake256x4_after_mlk_keccak_squeezeblocks_x4_1`
   (SHAKE256X4_PUBLIC SHAKE256X4_A2) THEN
  CONJ_TAC THENL [ALL_TAC; SHAKE256X4_SAFE_REST_TAC] THEN
  ENSURES_EVENTS_SEQUENCE_TAC
   `pc + mlkem_shake256x4_after_mlk_keccak_absorb_once_x4`
   (SHAKE256X4_PUBLIC SHAKE256X4_A1) THEN
  CONJ_TAC THENL [SHAKE256X4_SAFE_ABSORB_TAC; SHAKE256X4_SAFE_BLOCKS_TAC]);;
