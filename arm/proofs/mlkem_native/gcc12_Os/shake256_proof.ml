let ALIGNED_16_32_WORD_AND = prove
 (ALIGNED_16_32_WORD_AND_STMT,
  CONJ_TAC THEN GEN_TAC THEN REWRITE_TAC[aligned; DIMINDEX_64] THEN
  CONV_TAC NUM_REDUCE_CONV THEN
  CONV_TAC(ONCE_DEPTH_CONV DIVIDES_CONV) THEN REWRITE_TAC[] THENL
   [MP_TAC(ISPECL [`x:int64`; `4`] (CONJUNCT1 WORD_AND_MASK_WORD));
    MP_TAC(ISPECL [`x:int64`; `5`] (CONJUNCT1 WORD_AND_MASK_WORD))] THEN
  CONV_TAC(ONCE_DEPTH_CONV NUM_REDUCE_CONV) THEN DISCH_THEN SUBST1_TAC THEN
  REWRITE_TAC[DIVIDES_MOD; GSYM VAL_EQ_0; VAL_WORD; DIMINDEX_64] THEN
  SIMP_TAC[MOD_LT; ARITH_RULE `x MOD 16 < 16`; ARITH_RULE `x MOD 32 < 32`;
           ARITH_RULE `x < 16 ==> x < 2 EXP 64`;
           ARITH_RULE `x < 32 ==> x < 2 EXP 64`]);;

let SHAKE256_STATE_ADDRESS = prove
 (SHAKE256_STATE_ADDRESS_STMT,
  REWRITE_TAC[ALIGNED_16_32_WORD_AND] THEN GEN_TAC THEN
  COND_CASES_TAC THEN POP_ASSUM MP_TAC THEN
  W(fun (_,w) -> ACCEPT_TAC(BITBLAST_RULE w)));;

(*** The output from the squeezing of the state after absorbing, as shake256 ***)

let SHAKE256_OUTPUT_TAC =
  REWRITE_TAC[shake256] THEN AP_TERM_TAC THEN
  MATCH_MP_TAC LIST_OF_SEQ_EQ THEN X_GEN_TAC `i:num` THEN DISCH_TAC THEN
  REWRITE_TAC[] THEN CONV_TAC SYM_CONV THEN
  MP_TAC(SPECL [`512`; `31`; `inp:byte list`; `136`;
                `num_of_bytelist(inp:byte list) +
                 2 EXP (8 * LENGTH inp) *
                 num_of_bytelist(keccak_pad 136 31 (LENGTH inp))`; `i:num`]
               KECCAK_SPONGE_SQUEEZE) THEN
  ANTS_TAC THENL
   [REWRITE_TAC[] THEN CONV_TAC NUM_REDUCE_CONV; ALL_TAC] THEN
  DISCH_THEN SUBST1_TAC THEN REFL_TAC;;

let MLKEM_NATIVE_SHAKE256_GCC12_OS_IMAGE_SUBROUTINE_CORRECT = prove
 (MLKEM_NATIVE_SHAKE256_GCC12_OS_IMAGE_SUBROUTINE_CORRECT_STMT,
  MAP_EVERY X_GEN_TAC
   [`out:int64`; `outlen:num`; `m:int64`; `inp:byte list`; `guard:int64`;
    `mf:int64`; `ea:int64`; `el:num`; `ev:num`; `pc:num`] THEN
  WORD_FORALL_OFFSET_TAC 592 THEN
  MAP_EVERY X_GEN_TAC [`stackpointer:int64`; `returnaddress:int64`] THEN
  REWRITE_TAC[MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI; C_ARGUMENTS;
              ALL; ALLPAIRS; PAIRWISE; NONOVERLAPPING_CLAUSES] THEN
  DISCH_THEN(CONJUNCTS_THEN2
   (fun th -> ASSUME_TAC th THEN
              LABEL_TAC "H_MEMSET" (REWRITE_RULE[memset_contract] th))
   (REPEAT_TCL CONJUNCTS_THEN ASSUME_TAC)) THEN
  SHAKE256_SETUP_TAC THEN
  ENSURES_INIT_TAC "s0" THEN

  (*** Saving the registers and the stack guard, and the absorption ***)

  ARM_STEPS_TAC MLKEM_NATIVE_SHAKE256_GCC12_OS_EXEC (1--4) THEN
  MLKEM_NATIVE_ADRP_TAC THEN
  ARM_STEPS_TAC MLKEM_NATIVE_SHAKE256_GCC12_OS_EXEC (5--8) THEN
  SHAKE256_STATE_TAC THEN
  ARM_STEPS_TAC MLKEM_NATIVE_SHAKE256_GCC12_OS_EXEC (9--15) THEN
  ARM_SUBROUTINE_SIM_TAC
   (mlkem_native_libmlkem_gcc12_Os_mc,MLKEM_NATIVE_SHAKE256_GCC12_OS_EXEC,
    0x0,mlkem_native_libmlkem_gcc12_Os_mc,
    MLKEM_NATIVE_KECCAK_ABSORB_ONCE_GCC12_OS_IMAGE_SUBROUTINE_CORRECT)
   [`read X0 s`; `136`; `read X2 s`; `LENGTH(inp:byte list)`; `31`;
    `num_of_bytelist(inp:byte list)`; `mf:int64`; `ea:int64`; `el:num`;
    `ev:num`; `pc:num`; `read SP s`; `read X30 s`] 16 THEN

  (*** The squeezing of the output ***)

  ARM_STEPS_TAC MLKEM_NATIVE_SHAKE256_GCC12_OS_EXEC (17--21) THEN
  KECCAK_STATE_THEN SHAKE256_ST (fun v ->
    ARM_SUBROUTINE_SIM_TAC
     (mlkem_native_libmlkem_gcc12_Os_mc,MLKEM_NATIVE_SHAKE256_GCC12_OS_EXEC,
      0x0,mlkem_native_libmlkem_gcc12_Os_mc,
      MLKEM_NATIVE_KECCAK_SQUEEZE_ONCE_GCC12_OS_IMAGE_SUBROUTINE_CORRECT)
     [`read X0 s`; `outlen:num`; `read X2 s`; `136`; v; `pc:num`;
      `read SP s`; `read X30 s`] 22) THEN

  (*** Zeroing the state with memset ***)

  ARM_STEPS_TAC MLKEM_NATIVE_SHAKE256_GCC12_OS_EXEC (23--26) THEN
  RULE_ASSUM_TAC(REWRITE_RULE[SPECL [`pc:num`;
                                     `got_memset:num`] WORD_ADD]) THEN
  LIBC_PLT_TAC MLKEM_NATIVE_SHAKE256_GCC12_OS_EXEC 26 THEN
  LIBC_CALL_TAC "H_MEMSET" MLKEM_NATIVE_SHAKE256_GCC12_OS_EXEC
   [`read X0 s`; `read X1 s`; `read X2 s`; `read X30 s`] 31 THEN

  (*** The check of the stack guard and the return ***)

  ARM_STEPS_TAC MLKEM_NATIVE_SHAKE256_GCC12_OS_EXEC (32--32) THEN
  MLKEM_NATIVE_ADRP_TAC THEN
  ARM_STEPS_TAC MLKEM_NATIVE_SHAKE256_GCC12_OS_EXEC (33--41) THEN
  ENSURES_FINAL_STATE_TAC THEN ASM_REWRITE_TAC[] THEN
  SHAKE256_OUTPUT_TAC);;

let MLKEM_NATIVE_SHAKE256_GCC12_OS_IMAGE_SUBROUTINE_SAFE = time prove
 (MLKEM_NATIVE_SHAKE256_GCC12_OS_IMAGE_SUBROUTINE_SAFE_STMT,
  REPEAT GEN_TAC THEN DISCH_TAC THEN
  FIRST_ASSUM(fun th ->
    ASSUME_CALLEE_SAFETY_TAILED_TAC
     (MATCH_MP MLKEM_NATIVE_KECCAK_ABSORB_ONCE_GCC12_OS_IMAGE_SUBROUTINE_SAFE
               th)
     "H_ABSORB") THEN
  ASSUME_CALLEE_SAFETY_TAILED_TAC
    MLKEM_NATIVE_KECCAK_SQUEEZE_ONCE_GCC12_OS_IMAGE_SUBROUTINE_SAFE
    "H_SQUEEZE" THEN
  ASSUME_CALLEE_SAFETY_TAILED_TAC
    (REWRITE_RULE[memset_safety_contract]
      (ASSUME `memset_safety_contract (mf:int64) (ea:int64) (el:num) (ev:num)`))
    "H_MEMSET" THEN
  META_EXISTS_TAC THEN
  REPEAT_GEN_AND_OFFSET_STACKPTR_TAC THEN
  REWRITE_TAC[MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI; C_ARGUMENTS;
              ALL; ALLPAIRS; PAIRWISE; NONOVERLAPPING_CLAUSES] THEN
  DISCH_THEN(REPEAT_TCL CONJUNCTS_THEN ASSUME_TAC) THEN
  SHAKE256_SETUP_TAC THEN
  ENSURES_INIT_TAC "s0" THEN
  ARM_STEPS_TAC MLKEM_NATIVE_SHAKE256_GCC12_OS_EXEC (1--4) THEN
  MLKEM_NATIVE_ADRP_TAC THEN
  ARM_STEPS_TAC MLKEM_NATIVE_SHAKE256_GCC12_OS_EXEC (5--8) THEN
  SHAKE256_STATE_TAC THEN
  ARM_STEPS_TAC MLKEM_NATIVE_SHAKE256_GCC12_OS_EXEC (9--15) THEN
  SHAKE256_SAFE_CALL_TAC "H_ABSORB"
   [`e:(uarch_event)list`; `read X0 s`; `136`; `read X2 s`; `inlen:num`;
    `31`; `pc:num`; `read SP s`; `read X30 s`] 16 THEN
  ARM_STEPS_TAC MLKEM_NATIVE_SHAKE256_GCC12_OS_EXEC (17--21) THEN
  SHAKE256_SAFE_CALL_TAC "H_SQUEEZE"
   [`e:(uarch_event)list`; `read X0 s`; `outlen:num`; `read X2 s`; `136`;
    `pc:num`; `read SP s`; `read X30 s`] 22 THEN
  ARM_STEPS_TAC MLKEM_NATIVE_SHAKE256_GCC12_OS_EXEC (23--26) THEN
  RULE_ASSUM_TAC(REWRITE_RULE[SPECL [`pc:num`;
                                     `got_memset:num`] WORD_ADD]) THEN
  LIBC_PLT_TAC MLKEM_NATIVE_SHAKE256_GCC12_OS_EXEC 26 THEN
  LIBC_SAFE_CALL_TAC "H_MEMSET" MLKEM_NATIVE_SHAKE256_GCC12_OS_EXEC
   [`e:(uarch_event)list`; `read X0 s`; `read X1 s`; `read X2 s`;
    `read X30 s`]
   (ref [`pc:num`; `m:int64`; `out:int64`; `outlen:num`; `inlen:num`;
         `guard:int64`; `mf:int64`; `stackpointer:int64`;
         `returnaddress:int64`])
   31 THEN
  ARM_STEPS_TAC MLKEM_NATIVE_SHAKE256_GCC12_OS_EXEC (32--32) THEN
  MLKEM_NATIVE_ADRP_TAC THEN
  ARM_STEPS_TAC MLKEM_NATIVE_SHAKE256_GCC12_OS_EXEC (33--41) THEN
  ENSURES_FINAL_STATE_TAC THEN ASM_REWRITE_TAC[] THEN
  DISCHARGE_SAFETY_PROPERTY_TAC);;
