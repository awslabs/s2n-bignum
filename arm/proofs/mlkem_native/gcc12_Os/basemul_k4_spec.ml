(* ========================================================================= *)
(* Scalar product of 4-element polynomial vectors in NTT domain.             *)
(* This is the code for mlkem1024_polyvec_basemul_acc_montgomery_cached from *)
(* mlkem-native's portable C implementation compiled by gcc 12 with -Os      *)
(* (see mlkem_native/README.md). It has the two nested loops of the -O2      *)
(* code, an outer loop over the 128 pairs of coefficients of the output and  *)
(* an inner loop of 4 iterations over the polynomials of the vectors that    *)
(* accumulates the two sums in registers, with other registers and another   *)
(* order of instructions. It uses X0 to X17 only, so it does not change      *)
(* X18. It is verified in the whole image (see libmlkem.ml), with the same   *)
(* statements as the -O2 code.                                               *)
(* ========================================================================= *)

needs "arm/proofs/mlkem_native/relative.ml";;
