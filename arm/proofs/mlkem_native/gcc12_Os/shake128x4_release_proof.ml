needs "arm/proofs/mlkem_native/gcc12_Os/shake128x4_release_spec.ml";;


let MLKEM_NATIVE_SHAKE128X4_RELEASE_GCC12_OS_IMAGE_SUBROUTINE_CORRECT = prove
 (MLKEM_NATIVE_SHAKE128X4_RELEASE_GCC12_OS_IMAGE_SUBROUTINE_CORRECT_STMT,
  REWRITE_TAC[MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI; C_ARGUMENTS;
              ALL; ALLPAIRS; NONOVERLAPPING_CLAUSES] THEN
  REPEAT STRIP_TAC THEN ENSURES_INIT_TAC "s0" THEN
  ARM_STEPS_TAC MLKEM_NATIVE_SHAKE128X4_RELEASE_GCC12_OS_EXEC (1--2) THEN
  ARM_SUBROUTINE_SIM_TAC
   (mlkem_native_libmlkem_gcc12_Os_mc,
    MLKEM_NATIVE_SHAKE128X4_RELEASE_GCC12_OS_EXEC,
    0x0,mlkem_native_libmlkem_gcc12_Os_mc,
    MLKEM_NATIVE_ZEROIZE_3_GCC12_OS_IMAGE_SUBROUTINE_CORRECT)
   [`read X0 s`; `800`; `mf:int64`; `ea:int64`; `el:num`; `ev:num`;
    `pc:num`; `read SP s`; `read X30 s`] 3 THEN
  ENSURES_FINAL_STATE_TAC THEN ASM_REWRITE_TAC[]);;

let MLKEM_NATIVE_SHAKE128X4_RELEASE_GCC12_OS_IMAGE_SUBROUTINE_SAFE = time prove
 (MLKEM_NATIVE_SHAKE128X4_RELEASE_GCC12_OS_IMAGE_SUBROUTINE_SAFE_STMT,
  REPEAT GEN_TAC THEN DISCH_TAC THEN
  FIRST_ASSUM(fun th ->
    ASSUME_CALLEE_SAFETY_TAILED_TAC
     (MATCH_MP MLKEM_NATIVE_ZEROIZE_3_GCC12_OS_IMAGE_SUBROUTINE_SAFE th)
     "H_ZEROIZE") THEN
  META_EXISTS_TAC THEN
  REPEAT_GEN_AND_OFFSET_STACKPTR_TAC THEN
  REWRITE_TAC[MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI; C_ARGUMENTS;
              ALL; ALLPAIRS; NONOVERLAPPING_CLAUSES] THEN
  DISCH_THEN(REPEAT_TCL CONJUNCTS_THEN ASSUME_TAC) THEN
  ENSURES_INIT_TAC "s0" THEN
  ARM_STEPS_TAC MLKEM_NATIVE_SHAKE128X4_RELEASE_GCC12_OS_EXEC (1--2) THEN
  REMOVE_THEN "H_ZEROIZE" (fun safety_th ->
    ARM_SUBROUTINE_SIM_TAC ~is_safety_thm:true
      (mlkem_native_libmlkem_gcc12_Os_mc,
       MLKEM_NATIVE_SHAKE128X4_RELEASE_GCC12_OS_EXEC,
       0x0,mlkem_native_libmlkem_gcc12_Os_mc,safety_th)
      [`e:(uarch_event)list`; `read X0 s`; `800`; `pc:num`; `read SP s`;
       `read X30 s`] 3 THENL
     [EXISTS_E2_TAC (ref [`pc:num`; `st:int64`; `mf:int64`;
                          `stackpointer:int64`; `returnaddress:int64`]);
      LABEL_TAC "H_ZEROIZE" safety_th]) THEN
  ENSURES_FINAL_STATE_TAC THEN ASM_REWRITE_TAC[] THEN
  DISCHARGE_SAFETY_PROPERTY_TAC);;
