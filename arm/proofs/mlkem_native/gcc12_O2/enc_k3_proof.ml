needs "arm/proofs/mlkem_native/gcc12_O2/enc_k3_spec.ml";;


let KER3_BUFFER_ADDRESS = prove
 (KER3_BUFFER_ADDRESS_STMT,
  REWRITE_TAC[REJ_ALIGNED_16_32] THEN GEN_TAC THEN
  COND_CASES_TAC THEN POP_ASSUM MP_TAC THEN
  W(fun (_,w) -> ACCEPT_TAC(BITBLAST_RULE w)));;

let MLKEM_NATIVE_ENC_K3_GCC12_O2_IMAGE_SUBROUTINE_CORRECT = prove
 (MLKEM_NATIVE_ENC_K3_GCC12_O2_IMAGE_SUBROUTINE_CORRECT_STMT,
  KER3_INTRO_TAC THEN ASM_CASES_TAC `aligned 32 (stackpointer:int64)` THENL
   [KER3_CASE_TAC 17184; KER3_CASE_TAC 17168]);;

let MLKEM_NATIVE_ENC_K3_GCC12_O2_IMAGE_SUBROUTINE_SAFE = prove
 (MLKEM_NATIVE_ENC_K3_GCC12_O2_IMAGE_SUBROUTINE_SAFE_STMT,
  KER3_SAFE_INTRO_TAC THEN
  ASM_CASES_TAC `aligned 32 (stackpointer:int64)` THENL
   [KER3_SAFE_CASE_TAC 17184; KER3_SAFE_CASE_TAC 17168]);;
