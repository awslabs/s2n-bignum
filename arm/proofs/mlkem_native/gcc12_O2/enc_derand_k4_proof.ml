needs "arm/proofs/mlkem_native/gcc12_O2/enc_derand_k4_spec.ml";;


let MLKEM_EK_CHECK_1024 = prove
 (MLKEM_EK_CHECK_1024_STMT,
  SIMP_TAC[mlkem1024; MLKEM_EK_CHECK] THEN CONV_TAC NUM_REDUCE_CONV);;

let KE4_CHECK_EQ = prove
 (KE4_CHECK_EQ_STMT,
  GEN_TAC THEN AP_TERM_TAC THEN ABS_TAC THEN
  MATCH_MP_TAC(TAUT `(p ==> (q <=> r)) ==> (p ==> q <=> p ==> r)`) THEN
  DISCH_TAC THEN AP_THM_TAC THEN AP_TERM_TAC THEN
  MATCH_MP_TAC DIV_MOD_EXP_LOW THEN ASM_ARITH_TAC);;

let KE4_BUFFER_ADDRESS = prove
 (KE4_BUFFER_ADDRESS_STMT,
  REWRITE_TAC[REJ_ALIGNED_16_32] THEN GEN_TAC THEN
  COND_CASES_TAC THEN POP_ASSUM MP_TAC THEN
  W(fun (_,w) -> ACCEPT_TAC(BITBLAST_RULE w)));;

let MLKEM_NATIVE_ENC_DERAND_K4_GCC12_O2_IMAGE_SUBROUTINE_CORRECT = prove
 (MLKEM_NATIVE_ENC_DERAND_K4_GCC12_O2_IMAGE_SUBROUTINE_CORRECT_STMT,
  KE4_INTRO_TAC THEN ASM_CASES_TAC `aligned 32 (stackpointer:int64)` THENL
   [KE4_CASE_TAC 22912; KE4_CASE_TAC 22896]);;

let MLKEM_NATIVE_ENC_DERAND_K4_GCC12_O2_IMAGE_SUBROUTINE_SAFE = prove
 (MLKEM_NATIVE_ENC_DERAND_K4_GCC12_O2_IMAGE_SUBROUTINE_SAFE_STMT,
  KE4_SAFE_INTRO_TAC THEN ASM_CASES_TAC `aligned 32 (stackpointer:int64)` THENL
   [KE4_SAFE_CASE_TAC 22912; KE4_SAFE_CASE_TAC 22896]);;
