(* ========================================================================= *)
(* Tests of common/elf_image.ml and arm/proofs/libc.ml on a small shared     *)
(* object, libplt_demo.so, built by arm/plt_demo/build.sh from               *)
(* arm/plt_demo/src/plt_demo.S with the link options of the snappy build     *)
(* (-shared -Bsymbolic -z now -z relro). Its image is transcribed in         *)
(* arm/plt_demo/plt_demo.S; its RELRO data (0x1fe38, 0x1c8 bytes) has the     *)
(* slots of plt_demo_relocated (plt_demo_relocs.ml), as readelf -r lists:    *)
(*                                                                           *)
(*   0x1fe48 R_AARCH64_RELATIVE   0x370 (answer)    a "vtable" entry          *)
(*   0x1fe50 R_AARCH64_ABS64      memmove + 8                                 *)
(*   0x1fff8 R_AARCH64_GLOB_DAT   memcpy                                      *)
(*   0x1ffe0 R_AARCH64_JUMP_SLOT  memmove                                     *)
(*   0x1ffe8 R_AARCH64_JUMP_SLOT  memcpy                                      *)
(*                                                                           *)
(* The library spans 0x20000 bytes from pc (the end of the RELRO part).      *)
(*                                                                           *)
(* The functions, with the PLT stubs at 0x310 (memmove) and 0x320 (memcpy):  *)
(*                                                                           *)
(*   shift_copy (0x330): (a, b, len) |-> memmove(a, a + 8, len), then a tail  *)
(*     call memcpy(b, a, len), so both a and b get the len bytes that were   *)
(*     at a + 8, and it returns b.                                           *)
(*   answer (0x370): returns 42.                                             *)
(*   call_slot (0x378): a tail call through the RELATIVE slot at 0x1fe48,    *)
(*     i.e. to answer, as a virtual call through a vtable.                   *)
(*   memcpy_address (0x388): returns the GLOB_DAT slot, imp "memcpy".        *)
(*                                                                           *)
(*      0x330: stp  x29, x30, [sp, #-48]!     0x354: mov  x2, x21              *)
(*      0x334: mov  x29, sp                   0x358: mov  x1, x19              *)
(*      0x338: stp  x19, x20, [sp, #16]       0x35c: mov  x0, x20              *)
(*      0x33c: str  x21, [sp, #32]            0x360: ldp  x19, x20, [sp, #16]  *)
(*      0x340: mov  x19, x0                   0x364: ldr  x21, [sp, #32]       *)
(*      0x344: mov  x20, x1                   0x368: ldp  x29, x30, [sp], #48  *)
(*      0x348: mov  x21, x2                   0x36c: b    memcpy@plt           *)
(*      0x34c: add  x1, x0, #0x8                                             *)
(*      0x350: bl   memmove@plt                                              *)
(* ========================================================================= *)

needs "arm/proofs/libc.ml";;

let plt_demo_mc = define_from_elf "plt_demo_mc" "arm/plt_demo/plt_demo.o";;

(* The ELF header and the dynamic tables at the start of the image are not   *)
(* instructions, so only the code, the PLT and .text (0x2f0 to 0x394), is    *)
(* decoded.                                                                  *)

let PLT_DEMO_EXEC = ARM_MK_EXEC_RANGES_RULE plt_demo_mc [0x2f0,0x394];;

(* The relocated slots, plt_demo_relocated pc imp, generated by              *)
(* tools/elf_relocs.py (see arm/plt_demo/build.sh).                          *)

needs "arm/proofs/plt_demo_relocs.ml";;

(* The slots are in the RELRO data.                                          *)

let PLT_DEMO_SLOTS_WITHIN = prove
 (`!pc imp. elf_slots_within (word(pc + 0x1fe38)) 0x1c8
                             (plt_demo_relocated pc imp)`,
  REPEAT GEN_TAC THEN
  CONV_TAC(ELF_SLOTS_WITHIN_CONV ~defs:[plt_demo_relocated]));;

(* The slots from the state form (ELF_RELOCATED_TAC), and from the data     *)
(* form with its region (ELF_RELOCATED_DATA_TAC).                            *)

let PLT_DEMO_GOT_SLOTS = prove
 (`!pc imp s:armstate.
        elf_relocated memory s (plt_demo_relocated pc imp)
        ==> read (memory :> bytes64 (word_add (word pc) (word 0x1ffe8))) s =
            imp "memcpy" /\
            read (memory :> bytes64 (word_add (word pc) (word 0x1fe48))) s =
            word(pc + 0x370)`,
  REPEAT GEN_TAC THEN DISCH_TAC THEN
  ELF_RELOCATED_TAC ~defs:[plt_demo_relocated] THEN ASM_REWRITE_TAC[]);;

let PLT_DEMO_GOT_SLOTS_DATA = prove
 (`!pc imp rw s:armstate.
        elf_relocated_data (word(pc + 0x1fe38)) rw (plt_demo_relocated pc imp) /\
        read (memory :> bytes(word(pc + 0x1fe38),0x1c8)) s = rw
        ==> read (memory :> bytes64 (word_add (word pc) (word 0x1fe50))) s =
            word_add (imp "memmove") (word 8)`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  ELF_RELOCATED_DATA_TAC ~defs:[plt_demo_relocated]
    ~select:(elf_slots_at [0x1fe50]) THEN
  ASM_REWRITE_TAC[]);;

(* ------------------------------------------------------------------------- *)
(* The specification of shift_copy, in the form for proofs (the RELRO data   *)
(* as a region with contents rw, elf_relocated_data as a hypothesis), with   *)
(* the contracts of memmove and memcpy at the addresses imp "memmove" and    *)
(* imp "memcpy" that the GOT holds.                                          *)
(* ------------------------------------------------------------------------- *)

(* The statements share their hypotheses, precondition and frame, written  *)
(* once as text.                                                             *)

let shift_copy_hyps =
 "aligned 4096 (word pc:int64) /\\ pc + 0x20000 <= 2 EXP 64 /\\
  aligned 16 stackpointer /\\
  elf_relocated_data (word(pc + 0x1fe38)) rw (plt_demo_relocated pc imp) /\\
  nonoverlapping (b,val(len:int64)) (a,8 + val len) /\\
  nonoverlapping (word_sub stackpointer (word 48),48) (a,8 + val len) /\\
  nonoverlapping (word_sub stackpointer (word 48),48) (b,val len) /\\
  ALLPAIRS nonoverlapping
   [a,8 + val len; b,val len; word_sub stackpointer (word 48),48]
   [word pc,0x20000; ea,el]";;

let shift_copy_pre =
 "aligned_bytes_loaded s (word pc) plt_demo_mc /\\
  read PC s = word(pc + 0x330) /\\
  read SP s = stackpointer /\\
  read X30 s = returnaddress /\\
  C_ARGUMENTS [a; b; len] s /\\
  read (memory :> bytes(word(pc + 0x1fe38),0x1c8)) s = rw /\\
  read (memory :> bytes(ea,el)) s = ev";;

let shift_copy_frame =
 "MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI ,, MAYCHANGE [X18; X30] ,,
  MAYCHANGE [memory :> bytes(a,val(len:int64));
             memory :> bytes(b,val len);
             memory :> bytes(word_sub stackpointer (word 48),48)]";;

let SHIFT_COPY_CORRECT_STMT = parse_term
 ("!a b len y pc imp ea el ev rw stackpointer returnaddress.
     memmove_contract (imp \"memmove\") ea el ev /\\
     memcpy_contract (imp \"memcpy\") ea el ev /\\ " ^ shift_copy_hyps ^ "
     ==> ensures arm
          (\\s. " ^ shift_copy_pre ^ " /\\
               read (memory :> bytes(word_add a (word 8),val len)) s = y)
          (\\s. read PC s = returnaddress /\\ C_RETURN s = b /\\
               read (memory :> bytes(a,val len)) s = y /\\
               read (memory :> bytes(b,val len)) s = y)
          (" ^ shift_copy_frame ^ ")");;

let WORD_SUB_ADD_CANCEL = WORD_RULE `word_add (word_sub x y) y:int64 = x`;;

(* The start of both proofs: the contracts labelled, the callee-saved        *)
(* registers preserved, the slots of the GOT for memmove and memcpy as       *)
(* facts.                                                                    *)

let SHIFT_COPY_START_TAC =
  MAP_EVERY X_GEN_TAC
   [`a:int64`; `b:int64`; `len:int64`; `y:num`; `pc:num`;
    `imp:string->int64`; `ea:int64`; `el:num`; `ev:num`; `rw:num`;
    `stackpointer:int64`; `returnaddress:int64`] THEN
  REWRITE_TAC[MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI; C_ARGUMENTS; C_RETURN;
              ALL; ALLPAIRS; NONOVERLAPPING_CLAUSES] THEN
  DISCH_THEN(CONJUNCTS_THEN2
   (LABEL_TAC "H_MEMMOVE" o REWRITE_RULE[memmove_contract])
   (CONJUNCTS_THEN2 (LABEL_TAC "H_MEMCPY" o REWRITE_RULE[memcpy_contract])
                    (REPEAT_TCL CONJUNCTS_THEN ASSUME_TAC))) THEN
  ENSURES_EXISTING_PRESERVED_TAC `SP` THEN
  ENSURES_PRESERVED_TAC "x19_init" `X19` THEN
  ENSURES_PRESERVED_TAC "x20_init" `X20` THEN
  ENSURES_PRESERVED_TAC "x21_init" `X21` THEN
  ENSURES_PRESERVED_TAC "x29_init" `X29` THEN
  ENSURES_INIT_TAC "s0" THEN
  ELF_RELOCATED_DATA_TAC ~defs:[plt_demo_relocated]
    ~select:(elf_slots_importing ["memmove"; "memcpy"]) THEN
  DISCARD_MATCHING_ASSUMPTIONS
   [`read (memory :> bytes(word(pc + 0x1fe38),0x1c8)) s = rw`];;

(* With ARM_STEPS_TAC.                                                        *)

let SHIFT_COPY_CORRECT = prove
 (SHIFT_COPY_CORRECT_STMT,
  SHIFT_COPY_START_TAC THEN
  ARM_STEPS_TAC PLT_DEMO_EXEC (1--9) THEN
  ARM_PLT_STUB_TAC PLT_DEMO_EXEC 9 THEN
  ARM_PLT_CALL_TAC "H_MEMMOVE" PLT_DEMO_EXEC
   [`read X0 s`; `read X1 s`; `read X2 s`; `y:num`; `read X30 s`] 14 THEN
  ARM_STEPS_TAC PLT_DEMO_EXEC (15--21) THEN
  ARM_PLT_STUB_TAC PLT_DEMO_EXEC 21 THEN
  ARM_PLT_CALL_TAC "H_MEMCPY" PLT_DEMO_EXEC
   [`read X0 s`; `read X1 s`; `read X2 s`; `y:num`; `read X30 s`] 26 THEN
  ENSURES_FINAL_STATE_TAC THEN ASM_REWRITE_TAC[WORD_SUB_ADD_CANCEL]);;

(* With bstep: each block goes on through the PLT stub (its adrp and the     *)
(* ldr of the GOT slot), up to the call of the contract.                     *)

let SHIFT_COPY_CORRECT_BSTEP = prove
 (SHIFT_COPY_CORRECT_STMT,
  SHIFT_COPY_START_TAC THEN
  ARM_BSTEP_TAC PLT_DEMO_EXEC (1--13) THEN
  USE_THEN "H_MEMMOVE" (fun th ->
    ARM_BSTEP_PLT_CALL_TAC PLT_DEMO_EXEC th
     [`read X0 s`; `read X1 s`; `read X2 s`; `y:num`; `read X30 s`] "s14") THEN
  ARM_BSTEP_TAC PLT_DEMO_EXEC (15--25) THEN
  USE_THEN "H_MEMCPY" (fun th ->
    ARM_BSTEP_PLT_CALL_TAC PLT_DEMO_EXEC th
     [`read X0 s`; `read X1 s`; `read X2 s`; `y:num`; `read X30 s`] "s26") THEN
  BSTEP_FINAL_TAC THEN ASM_REWRITE_TAC[WORD_SUB_ADD_CANCEL]);;

(* ------------------------------------------------------------------------- *)
(* Memory safety of shift_copy, from the memory-safety contracts: the        *)
(* accesses are within the inputs, the stack frame, the library and (ea,el), *)
(* the writes within the outputs and the frame. No claim about what the       *)
(* events depend on.                                                         *)
(* ------------------------------------------------------------------------- *)

let SHIFT_COPY_SAFE_STMT = parse_term
 ("!a b len pc imp ea el ev rw stackpointer returnaddress e.
     memmove_safe_contract (imp \"memmove\") ea el ev /\\
     memcpy_safe_contract (imp \"memcpy\") ea el ev /\\ " ^ shift_copy_hyps ^ "
     ==> ensures arm
          (\\s. " ^ shift_copy_pre ^ " /\\ read events s = e)
          (\\s. read PC s = returnaddress /\\
               ?e2. read events s = APPEND e2 e /\\
                    memaccess_inbounds e2
                     [a,8 + val len; b,val len;
                      word_sub stackpointer (word 48),48;
                      word pc,0x20000; ea,el]
                     [a,val len; b,val len;
                      word_sub stackpointer (word 48),48])
          (" ^ shift_copy_frame ^ ")");;

let SHIFT_COPY_SAFE = prove
 (SHIFT_COPY_SAFE_STMT,
  MAP_EVERY X_GEN_TAC
   [`a:int64`; `b:int64`; `len:int64`; `pc:num`;
    `imp:string->int64`; `ea:int64`; `el:num`; `ev:num`; `rw:num`;
    `stackpointer:int64`; `returnaddress:int64`; `e:(uarch_event)list`] THEN
  REWRITE_TAC[MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI; C_ARGUMENTS; C_RETURN;
              ALL; ALLPAIRS; NONOVERLAPPING_CLAUSES] THEN
  DISCH_THEN(CONJUNCTS_THEN2
   (LABEL_TAC "H_MEMMOVE" o REWRITE_RULE[memmove_safe_contract])
   (CONJUNCTS_THEN2 (LABEL_TAC "H_MEMCPY" o
                     REWRITE_RULE[memcpy_safe_contract])
                    (REPEAT_TCL CONJUNCTS_THEN ASSUME_TAC))) THEN
  ENSURES_EXISTING_PRESERVED_TAC `SP` THEN
  ENSURES_PRESERVED_TAC "x19_init" `X19` THEN
  ENSURES_PRESERVED_TAC "x20_init" `X20` THEN
  ENSURES_PRESERVED_TAC "x21_init" `X21` THEN
  ENSURES_PRESERVED_TAC "x29_init" `X29` THEN
  ENSURES_INIT_TAC "s0" THEN
  ELF_RELOCATED_DATA_TAC ~defs:[plt_demo_relocated]
    ~select:(elf_slots_importing ["memmove"; "memcpy"]) THEN
  DISCARD_MATCHING_ASSUMPTIONS
   [`read (memory :> bytes(word(pc + 0x1fe38),0x1c8)) s = rw`] THEN
  ARM_BSTEP_TAC PLT_DEMO_EXEC (1--9) THEN
  USE_THEN "H_MEMMOVE" (fun th ->
    ARM_BSTEP_PLT_TAC PLT_DEMO_EXEC th
     [`read events s`; `read X0 s`; `read X1 s`; `read X2 s`;
      `read X30 s`] "s14") THEN
  ARM_BSTEP_TAC PLT_DEMO_EXEC (15--21) THEN
  USE_THEN "H_MEMCPY" (fun th ->
    ARM_BSTEP_PLT_TAC PLT_DEMO_EXEC th
     [`read events s`; `read X0 s`; `read X1 s`; `read X2 s`;
      `read X30 s`] "s26") THEN
  BSTEP_FINAL_TAC THEN ASM_REWRITE_TAC[WORD_SUB_ADD_CANCEL] THEN
  MEMSAFE_EVENTS_TAC);;

(* ------------------------------------------------------------------------- *)
(* A call through the RELATIVE slot (ARM_STEPS_TAC), and the GLOB_DAT slot   *)
(* (bstep, one block through the ADRP).                                      *)
(* ------------------------------------------------------------------------- *)

let CALL_SLOT_CORRECT = prove
 (`!pc imp rw returnaddress.
        aligned 4096 (word pc:int64) /\
        elf_relocated_data (word(pc + 0x1fe38)) rw (plt_demo_relocated pc imp)
        ==> ensures arm
             (\s. aligned_bytes_loaded s (word pc) plt_demo_mc /\
                  read PC s = word(pc + 0x378) /\
                  read X30 s = returnaddress /\
                  read (memory :> bytes(word(pc + 0x1fe38),0x1c8)) s = rw)
             (\s. read PC s = returnaddress /\ C_RETURN s = word 42)
             (MAYCHANGE [PC; X0; X16] ,, MAYCHANGE [events])`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN REWRITE_TAC[C_RETURN] THEN
  ENSURES_INIT_TAC "s0" THEN
  ELF_RELOCATED_DATA_TAC ~defs:[plt_demo_relocated]
    ~select:(elf_slots_at [0x1fe48]) THEN
  ARM_STEPS_TAC PLT_DEMO_EXEC [1] THEN IMAGE_ADRP_TAC THEN
  ARM_STEPS_TAC PLT_DEMO_EXEC (2--6) THEN
  ENSURES_FINAL_STATE_TAC THEN ASM_REWRITE_TAC[]);;

let MEMCPY_ADDRESS_CORRECT = prove
 (`!pc imp rw returnaddress.
        aligned 4096 (word pc:int64) /\
        elf_relocated_data (word(pc + 0x1fe38)) rw (plt_demo_relocated pc imp)
        ==> ensures arm
             (\s. aligned_bytes_loaded s (word pc) plt_demo_mc /\
                  read PC s = word(pc + 0x388) /\
                  read X30 s = returnaddress /\
                  read (memory :> bytes(word(pc + 0x1fe38),0x1c8)) s = rw)
             (\s. read PC s = returnaddress /\ C_RETURN s = imp "memcpy")
             (MAYCHANGE [PC; X0] ,, MAYCHANGE [events])`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN REWRITE_TAC[C_RETURN] THEN
  ENSURES_INIT_TAC "s0" THEN
  ELF_RELOCATED_DATA_TAC ~defs:[plt_demo_relocated]
    ~select:(elf_slots_at [0x1fff8]) THEN
  ARM_BSTEP_TAC PLT_DEMO_EXEC (1--3) THEN
  BSTEP_FINAL_TAC THEN ASM_REWRITE_TAC[]);;

(* ------------------------------------------------------------------------- *)
(* The entry-point form: the slots in the state (elf_relocated) instead of   *)
(* the contents of the RELRO data, by ENSURES_ELF_RELOCATED.                  *)
(* ------------------------------------------------------------------------- *)

let CALL_SLOT_RELOCATED = prove
 (`!pc imp returnaddress.
        aligned 4096 (word pc:int64)
        ==> ensures arm
             (\s. elf_relocated memory s (plt_demo_relocated pc imp) /\
                  aligned_bytes_loaded s (word pc) plt_demo_mc /\
                  read PC s = word(pc + 0x378) /\
                  read X30 s = returnaddress)
             (\s. read PC s = returnaddress /\ C_RETURN s = word 42)
             (MAYCHANGE [PC; X0; X16] ,, MAYCHANGE [events])`,
  REPEAT STRIP_TAC THEN
  ENSURES_ELF_RELOCATED_TAC `word(pc + 0x1fe38):int64` `0x1c8` THEN
  REWRITE_TAC[PLT_DEMO_SLOTS_WITHIN] THEN
  X_GEN_TAC `rw:num` THEN DISCH_TAC THEN
  MP_TAC(SPECL [`pc:num`; `imp:string->int64`; `rw:num`;
                `returnaddress:int64`] CALL_SLOT_CORRECT) THEN
  ASM_REWRITE_TAC[] THEN
  DISCH_THEN(MATCH_MP_TAC o MATCH_MP
   (ONCE_REWRITE_RULE[IMP_CONJ_ALT] ENSURES_PRECONDITION_THM)) THEN
  GEN_TAC THEN BETA_TAC THEN STRIP_TAC THEN ASM_REWRITE_TAC[]);;
