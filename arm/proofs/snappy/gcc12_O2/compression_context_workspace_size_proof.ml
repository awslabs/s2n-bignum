needs "arm/proofs/snappy/gcc12_O2/compression_context_workspace_size_spec.ml";;
needs "arm/proofs/heap_plt.ml";;

let SNAPPY_COMPRESSION_CONTEXT_WORKSPACE_SIZE_GCC12_O2_IMAGE_SUBROUTINE_SAFE = prove
 (SNAPPY_COMPRESSION_CONTEXT_WORKSPACE_SIZE_GCC12_O2_IMAGE_SUBROUTINE_SAFE_STMT,
  let exec = SNAPPY_COMPRESSION_CONTEXT_WORKSPACE_SIZE_GCC12_O2_EXEC in
  REWRITE_TAC[C_ARGUMENTS; C_RETURN; MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI] THEN
  REPEAT GEN_TAC THEN STRIP_TAC THEN ENSURES_INIT_TAC "s0" THEN
  ARM_BSTEP_TAC exec (1--4) THEN
  ARM_BSTEP_CONTRACT_TAC exec
    SNAPPY_WORKING_MEMORY_REQUIRED_SIZE_GCC12_O2_IMAGE_SUBROUTINE_SAFE
    [`read events s`; `read X0 s`; `pc:num`; `read SP s`; `read X30 s`;
     `read X19 s`; `read X20 s`; `read X29 s`] "s5" THEN
  ARM_BSTEP_TAC exec (6--8) THEN
  BSTEP_FINAL_TAC THEN ASM_REWRITE_TAC[] THEN REPEAT CONJ_TAC THENL
   [CONV_TAC WORD_RULE;
    REWRITE_TAC[GSYM WORD_ADD] THEN AP_TERM_TAC THEN ARITH_TAC;
    MEMACCESS_INSET_TAC]);;

let SNAPPY_COMPRESSION_CONTEXT_WORKSPACE_SIZE_GCC12_O2_IMAGE_SUBROUTINE_CORRECT = prove
 (SNAPPY_COMPRESSION_CONTEXT_WORKSPACE_SIZE_GCC12_O2_IMAGE_SUBROUTINE_CORRECT_STMT,
  ENSURES_DROP_EVENTS_TAC
    SNAPPY_COMPRESSION_CONTEXT_WORKSPACE_SIZE_GCC12_O2_IMAGE_SUBROUTINE_SAFE);;
