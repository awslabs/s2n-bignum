needs "arm/proofs/snappy/gcc12_O2/compression_context_operator_assign_spec.ml";;
needs "arm/proofs/heap_plt.ml";;

let SNAPPY_COMPRESSION_CONTEXT_OPERATOR_ASSIGN_SELF_GCC12_O2_IMAGE_SUBROUTINE_SAFE = prove
 (SNAPPY_COMPRESSION_CONTEXT_OPERATOR_ASSIGN_SELF_GCC12_O2_IMAGE_SUBROUTINE_SAFE_STMT,
  REWRITE_TAC[C_ARGUMENTS; C_RETURN; MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI] THEN
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SUBGOAL_THEN `val(word_sub (cc:int64) cc) = 0` ASSUME_TAC THENL
   [REWRITE_TAC[WORD_SUB_REFL; VAL_WORD_0]; ALL_TAC] THEN
  ENSURES_INIT_TAC "s0" THEN
  ARM_BSTEP_TAC SNAPPY_COMPRESSION_CONTEXT_OPERATOR_ASSIGN_GCC12_O2_EXEC (1--10) THEN
  BSTEP_FINAL_TAC THEN ASM_REWRITE_TAC[] THEN
  CONJ_TAC THENL [CONV_TAC WORD_RULE; MEMACCESS_INSET_TAC]);;

let SNAPPY_COMPRESSION_CONTEXT_OPERATOR_ASSIGN_SELF_GCC12_O2_IMAGE_SUBROUTINE_CORRECT = prove
 (SNAPPY_COMPRESSION_CONTEXT_OPERATOR_ASSIGN_SELF_GCC12_O2_IMAGE_SUBROUTINE_CORRECT_STMT,
  ENSURES_DROP_EVENTS_TAC
    SNAPPY_COMPRESSION_CONTEXT_OPERATOR_ASSIGN_SELF_GCC12_O2_IMAGE_SUBROUTINE_SAFE);;

(*** NULL: Reset of the empty context, then the move.                      ***)

let SNAPPY_COMPRESSION_CONTEXT_OPERATOR_ASSIGN_NULL_GCC12_O2_IMAGE_SUBROUTINE_SAFE = prove
 (SNAPPY_COMPRESSION_CONTEXT_OPERATOR_ASSIGN_NULL_GCC12_O2_IMAGE_SUBROUTINE_SAFE_STMT,
  let exec = SNAPPY_COMPRESSION_CONTEXT_OPERATOR_ASSIGN_GCC12_O2_EXEC in
  REWRITE_TAC[C_ARGUMENTS; C_RETURN; MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI;
              ALLPAIRS; ALL] THEN
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SUBGOAL_THEN `~(val(word_sub (cc:int64) other) = 0)` ASSUME_TAC THENL
   [ASM_REWRITE_TAC[VAL_EQ_0; WORD_SUB_EQ_0]; ALL_TAC] THEN
  ENSURES_INIT_TAC "s0" THEN
  ARM_BSTEP_TAC exec (1--8) THEN
  ARM_BSTEP_CONTRACT_TAC exec
    SNAPPY_COMPRESSION_CONTEXT_RESET_NULL_GCC12_O2_IMAGE_SUBROUTINE_SAFE
    [`read events s`; `read X0 s`; `pc:num`; `read SP s`; `read X30 s`;
     `read X19 s`; `read X20 s`; `read X29 s`] "s9" THEN
  ARM_BSTEP_TAC exec (10--18) THEN
  BSTEP_FINAL_TAC THEN ASM_REWRITE_TAC[] THEN
  CONJ_TAC THENL [CONV_TAC WORD_RULE; MEMACCESS_INSET_TAC]);;

let SNAPPY_COMPRESSION_CONTEXT_OPERATOR_ASSIGN_NULL_GCC12_O2_IMAGE_SUBROUTINE_CORRECT = prove
 (SNAPPY_COMPRESSION_CONTEXT_OPERATOR_ASSIGN_NULL_GCC12_O2_IMAGE_SUBROUTINE_CORRECT_STMT,
  ENSURES_DROP_EVENTS_TAC
    SNAPPY_COMPRESSION_CONTEXT_OPERATOR_ASSIGN_NULL_GCC12_O2_IMAGE_SUBROUTINE_SAFE);;
