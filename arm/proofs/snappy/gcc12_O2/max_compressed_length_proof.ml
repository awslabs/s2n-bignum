needs "arm/proofs/snappy/gcc12_O2/max_compressed_length_spec.ml";;
needs "arm/proofs/bstep.ml";;

(*** n DIV 6 as the code computes it: the high half of the product with   ***)
(*** 0xAAAAAAAAAAAAAAAB = (2^65 + 1) / 3, shifted right by 2, which is     ***)
(*** (n * (2^65 + 1)) DIV (3 * 2^66) = (2 * n + n / 2^64) DIV 12.          ***)

let MAGIC_DIV6 = prove
 (`!n. n < 2 EXP 64
       ==> (n * 12297829382473034411) DIV 18446744073709551616 DIV 4 =
           n DIV 6`,
  REPEAT STRIP_TAC THEN REWRITE_TAC[DIV_DIV] THEN CONV_TAC NUM_REDUCE_CONV THEN
  MP_TAC(SPECL [`n:num`; `6`] DIVISION) THEN REWRITE_TAC[ARITH_EQ] THEN
  ABBREV_TAC `q = n DIV 6` THEN ABBREV_TAC `r = n MOD 6` THEN STRIP_TAC THEN
  MATCH_MP_TAC DIV_UNIQ THEN
  EXISTS_TAC `n * 12297829382473034411 - q * 73786976294838206464` THEN
  ASM_ARITH_TAC);;

(*** The branch on n > 0xdb6db6db6db6db4e splits the proof in two; each   ***)
(*** straight-line part is run by bstep.                                 ***)

let SNAPPY_MAX_COMPRESSED_LENGTH_GCC12_O2_IMAGE_SUBROUTINE_CORRECT = prove
 (SNAPPY_MAX_COMPRESSED_LENGTH_GCC12_O2_IMAGE_SUBROUTINE_CORRECT_STMT,
  REWRITE_TAC[C_ARGUMENTS; C_RETURN; MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI;
              snappy_max_compressed_length_gcc12_O2_result; GT] THEN
  CONV_TAC NUM_REDUCE_CONV THEN
  W64_GEN_TAC `n:num` THEN
  MAP_EVERY X_GEN_TAC [`pc:num`; `returnaddress:int64`] THEN
  STRIP_TAC THEN ENSURES_INIT_TAC "s0" THEN
  ARM_STEPS_TAC SNAPPY_MAX_COMPRESSED_LENGTH_GCC12_O2_EXEC (1--6) THEN
  SUBGOAL_THEN
   `(15811494920322472782 <= n /\
     ~(val(word_sub (word n) (word 15811494920322472782):int64) = 0)) <=>
    15811494920322472782 < n`
   (fun th -> RULE_ASSUM_TAC(REWRITE_RULE[th])) THENL
   [REWRITE_TAC[VAL_EQ_0; WORD_SUB_EQ_0] THEN
    ONCE_REWRITE_TAC[GSYM VAL_EQ] THEN
    ASM_REWRITE_TAC[] THEN CONV_TAC WORD_REDUCE_CONV THEN ARITH_TAC;
    ALL_TAC] THEN
  ASM_CASES_TAC `15811494920322472782 < n` THEN
  POP_ASSUM(fun th -> RULE_ASSUM_TAC(REWRITE_RULE[th]) THEN ASSUME_TAC th) THEN
  ASM_REWRITE_TAC[] THENL
   [ARM_BSTEP_TAC SNAPPY_MAX_COMPRESSED_LENGTH_GCC12_O2_EXEC (7--8) THEN
    ENSURES_FINAL_STATE_TAC THEN ASM_REWRITE_TAC[];
    ARM_BSTEP_TAC SNAPPY_MAX_COMPRESSED_LENGTH_GCC12_O2_EXEC (7--12) THEN
    ENSURES_FINAL_STATE_TAC THEN ASM_REWRITE_TAC[] THEN
    REWRITE_TAC[word_ushr; VAL_WORD; DIMINDEX_64] THEN
    CONV_TAC NUM_REDUCE_CONV THEN
    SUBGOAL_THEN
     `(n * 12297829382473034411) DIV 18446744073709551616 <
      18446744073709551616`
     (fun th -> REWRITE_TAC[MATCH_MP MOD_LT th]) THENL
     [SIMP_TAC[RDIV_LT_EQ; ARITH_EQ] THEN
      UNDISCH_TAC `n < 2 EXP 64` THEN CONV_TAC NUM_REDUCE_CONV THEN ARITH_TAC;
      ASM_SIMP_TAC[MAGIC_DIV6] THEN REWRITE_TAC[GSYM WORD_ADD] THEN
      AP_TERM_TAC THEN ARITH_TAC]]);;

