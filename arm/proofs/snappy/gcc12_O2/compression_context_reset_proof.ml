needs "arm/proofs/snappy/gcc12_O2/compression_context_reset_spec.ml";;

(*** OWNED: wm is a live block, so it is not 0 (heap_props) and the cbz     ***)
(*** falls through; ~WorkingMemory is gone through by its contract with H,  ***)
(*** then delete wm with heap_remove mem H, in which (wm,48) is still live  ***)
(*** (MEM_HEAP_REMOVE_OTHER, wm <> mem).                                    ***)

let SNAPPY_COMPRESSION_CONTEXT_RESET_OWNED_GCC12_O2_IMAGE_SUBROUTINE_SAFE = prove
 (SNAPPY_COMPRESSION_CONTEXT_RESET_OWNED_GCC12_O2_IMAGE_SUBROUTINE_SAFE_STMT,
  let exec = SNAPPY_COMPRESSION_CONTEXT_RESET_GCC12_O2_EXEC in
  REWRITE_TAC[C_ARGUMENTS; C_RETURN; MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI;
              ALLPAIRS; ALL] THEN
  MAP_EVERY X_GEN_TAC
   [`heap_ok:(int64#num)list->(int64->byte)->bool`;
    `heap_fp:(int64#num)list->int64->bool`;
    `heap_room:(int64#num)list->num->bool`; `stk:num`] THEN
  DISCH_THEN(fun model ->
    ASSUME_TAC model THEN REPEAT GEN_TAC THEN STRIP_TAC THEN
    SUBGOAL_THEN `MEM (wm:int64,48) (heap_remove mem H)` ASSUME_TAC THENL
     [MATCH_MP_TAC MEM_HEAP_REMOVE_OTHER THEN ASM_REWRITE_TAC[FST]; ALL_TAC] THEN
    ENSURES_INIT_TAC "s0" THEN
    ELF_RELOCATED_DATA_TAC ~defs:[snappy_libsnappy_gcc12_O2_relocated]
      ~select:(elf_slots_importing ["_ZdlPv"]) THEN
    HEAP_BLOCK_NONZERO_TAC model THEN
    (* ~WorkingMemory, which frees mem *)
    ARM_BSTEP_TAC exec (1--10) THEN
    ARM_BSTEP_CONTRACT_TAC exec
      (MATCH_MP SNAPPY_WORKING_MEMORY_DTOR_OWNED_GCC12_O2_IMAGE_SUBROUTINE_SAFE
                model)
      [`read events s`; `read X0 s`; `mem:int64`; `m:num`; `pc:num`; `rw:num`;
       `H:(int64#num)list`; `read SP s`; `read X30 s`] "s11" THEN
    (* operator delete of wm *)
    ARM_BSTEP_TAC exec (12--13) THEN
    ARM_BSTEP_PLT_HEAP_DELETE_TAC exec model "s18" THEN
    ARM_BSTEP_TAC exec (19--22) THEN
    BSTEP_FINAL_TAC THEN ASM_REWRITE_TAC[] THEN
    REPEAT CONJ_TAC THEN
    FIRST [FOOTPRINT_SUBSET_TAC; MEMACCESS_INSET_TAC; CONV_TAC WORD_RULE]));;

let SNAPPY_COMPRESSION_CONTEXT_RESET_OWNED_GCC12_O2_IMAGE_SUBROUTINE_CORRECT = prove
 (SNAPPY_COMPRESSION_CONTEXT_RESET_OWNED_GCC12_O2_IMAGE_SUBROUTINE_CORRECT_STMT,
  ENSURES_DROP_EVENTS_TAC
    SNAPPY_COMPRESSION_CONTEXT_RESET_OWNED_GCC12_O2_IMAGE_SUBROUTINE_SAFE);;

(*** BORROWED: the destructor of the WorkingMemory that does not own its    ***)
(*** memory returns at once.                                                ***)

let SNAPPY_COMPRESSION_CONTEXT_RESET_BORROWED_GCC12_O2_IMAGE_SUBROUTINE_SAFE = prove
 (SNAPPY_COMPRESSION_CONTEXT_RESET_BORROWED_GCC12_O2_IMAGE_SUBROUTINE_SAFE_STMT,
  let exec = SNAPPY_COMPRESSION_CONTEXT_RESET_GCC12_O2_EXEC in
  REWRITE_TAC[C_ARGUMENTS; C_RETURN; MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI;
              ALLPAIRS; ALL] THEN
  REPEAT GEN_TAC THEN STRIP_TAC THEN
  SUBGOAL_THEN `~(val(wm:int64) = 0)` ASSUME_TAC THENL
   [ASM_REWRITE_TAC[VAL_EQ_0]; ALL_TAC] THEN
  ENSURES_INIT_TAC "s0" THEN
  ARM_BSTEP_TAC exec (1--10) THEN
  ARM_BSTEP_CONTRACT_TAC exec
    SNAPPY_WORKING_MEMORY_DTOR_BORROWED_GCC12_O2_IMAGE_SUBROUTINE_SAFE
    [`read events s`; `read X0 s`; `pc:num`; `read X30 s`] "s11" THEN
  ARM_BSTEP_TAC exec (12--16) THEN
  BSTEP_FINAL_TAC THEN ASM_REWRITE_TAC[] THEN
  CONJ_TAC THENL [CONV_TAC WORD_RULE; MEMACCESS_INSET_TAC]);;

let SNAPPY_COMPRESSION_CONTEXT_RESET_BORROWED_GCC12_O2_IMAGE_SUBROUTINE_CORRECT = prove
 (SNAPPY_COMPRESSION_CONTEXT_RESET_BORROWED_GCC12_O2_IMAGE_SUBROUTINE_CORRECT_STMT,
  ENSURES_DROP_EVENTS_TAC
    SNAPPY_COMPRESSION_CONTEXT_RESET_BORROWED_GCC12_O2_IMAGE_SUBROUTINE_SAFE);;

(*** NULL: the cbz goes to the epilogue.                                    ***)

