needs "arm/proofs/snappy/gcc12_O2/byte_array_source_peek_spec.ml";;
needs "arm/proofs/heap_plt.ml";;

(*** Straight-line code: bstep to the return.                              ***)

let SNAPPY_BYTE_ARRAY_SOURCE_PEEK_GCC12_O2_IMAGE_SUBROUTINE_SAFE = prove
 (SNAPPY_BYTE_ARRAY_SOURCE_PEEK_GCC12_O2_IMAGE_SUBROUTINE_SAFE_STMT,
  REWRITE_TAC[C_ARGUMENTS; C_RETURN; MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI] THEN
  REPEAT STRIP_TAC THEN ENSURES_INIT_TAC "s0" THEN
  ARM_BSTEP_TAC SNAPPY_BYTE_ARRAY_SOURCE_PEEK_GCC12_O2_EXEC (1--3) THEN
  BSTEP_FINAL_TAC THEN ASM_REWRITE_TAC[] THEN MEMACCESS_INSET_TAC);;

let SNAPPY_BYTE_ARRAY_SOURCE_PEEK_GCC12_O2_IMAGE_SUBROUTINE_CORRECT = prove
 (SNAPPY_BYTE_ARRAY_SOURCE_PEEK_GCC12_O2_IMAGE_SUBROUTINE_CORRECT_STMT,
  ENSURES_DROP_EVENTS_TAC SNAPPY_BYTE_ARRAY_SOURCE_PEEK_GCC12_O2_IMAGE_SUBROUTINE_SAFE);;
