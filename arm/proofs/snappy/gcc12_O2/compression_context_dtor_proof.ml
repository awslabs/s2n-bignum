needs "arm/proofs/snappy/gcc12_O2/compression_context_dtor_spec.ml";;

(*** One step, the branch to Reset, and then the contract of Reset in the  ***)
(*** same case, which returns to the caller of the destructor.             ***)

let SNAPPY_COMPRESSION_CONTEXT_DTOR_GCC12_O2_TAC (has_model:bool) (th:thm)
                                                 (ilist:term list) =
  let exec = SNAPPY_COMPRESSION_CONTEXT_DTOR_GCC12_O2_EXEC in
  let body model =
    REPEAT GEN_TAC THEN STRIP_TAC THEN ENSURES_INIT_TAC "s0" THEN
    ARM_BSTEP_TAC exec (1--1) THEN
    ARM_BSTEP_CONTRACT_TAC exec
      (match model with Some m -> MATCH_MP th m | None -> th) ilist "s2" THEN
    BSTEP_FINAL_TAC THEN ASM_REWRITE_TAC[] THEN TRY MEMACCESS_INSET_TAC in
  REWRITE_TAC[C_ARGUMENTS; C_RETURN; MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI;
              ALLPAIRS; ALL] THEN
  if has_model then
    MAP_EVERY X_GEN_TAC
     [`heap_ok:(int64#num)list->(int64->byte)->bool`;
      `heap_fp:(int64#num)list->int64->bool`;
      `heap_room:(int64#num)list->num->bool`; `stk:num`] THEN
    DISCH_THEN(fun model -> ASSUME_TAC model THEN body (Some model))
  else body None;;

let SNAPPY_COMPRESSION_CONTEXT_DTOR_OWNED_GCC12_O2_IMAGE_SUBROUTINE_SAFE = prove
 (SNAPPY_COMPRESSION_CONTEXT_DTOR_OWNED_GCC12_O2_IMAGE_SUBROUTINE_SAFE_STMT,
  SNAPPY_COMPRESSION_CONTEXT_DTOR_GCC12_O2_TAC true
    SNAPPY_COMPRESSION_CONTEXT_RESET_OWNED_GCC12_O2_IMAGE_SUBROUTINE_SAFE
    [`read events s`; `read X0 s`; `wm:int64`; `mem:int64`; `m:num`; `pc:num`;
     `rw:num`; `H:(int64#num)list`; `read SP s`; `read X30 s`; `read X19 s`;
     `read X20 s`; `read X29 s`]);;

