let AES128_GCM_ENC_ALT_NOIBT_SUBROUTINE_CORRECT = prove
 (`!in_p len_bits out_p tag_p ivec_p key_p htable_p
     inblock tag0 nonce c rk pc stackpointer returnaddress.
