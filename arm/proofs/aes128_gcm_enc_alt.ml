    ALLPAIRS nonoverlapping
      [(out_p, 16 * gcm_wb_blocks len_bits); (tag_p, 16); (ivec_p, 16);
       (word_sub stackpointer (word 80), 80)]
      [(word pc, LENGTH aes128_gcm_enc_alt_tmc); (key_p, 176);
