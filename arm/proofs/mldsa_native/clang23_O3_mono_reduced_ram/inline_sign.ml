(* ========================================================================= *)
(* Lemmas for the loops of verify_internal and signature_internal that clang *)
(* has inlined into them: one per shape of loop, stated from the head of the *)
(* loop to its exit, with the registers and addresses as parameters, so that *)
(* the proof of the caller uses it as it uses the theorem for a subroutine   *)
(* (FULL_CALL_TAC: the result is at a PC in the caller, not at a return).    *)
(*                                                                           *)
(* Each lemma is generated by a function of the image (the name of its       *)
(* constant), the EXEC theorem of the caller, the labels of the head and the *)
(* exit of the loop in the layout, and the registers, as in                  *)
(* mlkem_native/inline_loops.ml. The statement of each has the correctness   *)
(* and the events together, as the FULL theorems of the functions:           *)
(*                                                                           *)
(*   exists f_events. forall e a ... pc. ... ==> ensures arm                 *)
(*     (\s. ... read PC s = word(pc + head) /\ <registers> /\ <input> /\     *)
(*          read events s = e)                                               *)
(*     (\s. read PC s = word(pc + exit) /\ <registers> /\ <result> /\        *)
(*          exists e2. read events s = APPEND e2 e /\ e2 = f_events ... /\    *)
(*                     memaccess_inbounds e2 ...)                            *)
(*     (MAYCHANGE <registers of the loop> ,, ...)                            *)
(* ========================================================================= *)

needs "arm/proofs/mlkem_native/relative.ml";;
needs "arm/proofs/utils/mldsa_native.ml";;
needs "arm/proofs/utils/mldsa_native_full.ml";;
needs "common/mldsa_native_poly.ml";;
needs "arm/proofs/mldsa_native/clang23_O3_mono_reduced_ram/libmldsa.ml";;

(* ------------------------------------------------------------------------- *)
(* poly_pointwise_montgomery, as clang -O3 has inlined it (27 instances):    *)
(* a := a * b pointwise in the Montgomery domain, in 64 iterations of 4      *)
(* coefficients, with scalar loads (LDPSW, LDURSW), 64-bit products and the  *)
(* Montgomery reduction by SMADDL, with the constants q^-1 * 2^32 (in QI)    *)
(* and -q (in NQ) in registers. B8 holds b + 8, which the loop uses to read  *)
(* the coefficients 1 to 3 of b.                                             *)
(* ------------------------------------------------------------------------- *)

let INLINE_PWM_LOOP_TERM mc loop exit areg breg b8reg ireg qireg nqreg
                         (modregs:string list) =
  parse_term(Printf.sprintf
   "exists f_events.
      forall e a b (x:num->int32) (y:num->int32) pc.
        aligned 4096 (word pc:int64) /\\ pc + libmldsa_size <= 2 EXP 64 /\\
        ALL (nonoverlapping (a,1024)) [(word pc,libmldsa_size); (b,1024)]
        ==> ensures arm
             (\\s. aligned_bytes_loaded s (word pc) %s /\\
                  read PC s = word (pc + %s) /\\
                  read %s s = a /\\ read %s s = b /\\
                  read %s s = word_add b (word 8) /\\
                  read %s s = word 0 /\\
                  read %s s = word 0x0380200100000000 /\\
                  read %s s = word 0xffffffffff801fff /\\
                  (!i. i < 256
                       ==> read(memory :> bytes32(word_add a (word(4 * i))))
                             s = x i) /\\
                  (!i. i < 256
                       ==> read(memory :> bytes32(word_add b (word(4 * i))))
                             s = y i) /\\
                  read events s = e)
             (\\s. read PC s = word (pc + %s) /\\
                  read %s s = word 1024 /\\
                  (!i. i < 256
                       ==> read(memory :> bytes32(word_add a (word(4 * i))))
                             s = mld_poly_pointwise_montgomery x y i) /\\
                  (exists e2.
                     read events s = APPEND e2 e /\\
                     e2 = f_events a b pc /\\
                     memaccess_inbounds e2 [a,1024; b,1024] [a,1024]))
             (MAYCHANGE [PC; %s] ,, MAYCHANGE SOME_FLAGS ,,
              MAYCHANGE [events] ,, MAYCHANGE [memory :> bytes(a,1024)])"
   mc loop areg breg b8reg ireg qireg nqreg exit ireg
   (String.concat "; " modregs));;

(*** The exit of a loop, where the loop invariant gives the postcondition ***)

let INLINE_EXIT_TAC =
  REWRITE_TAC[] THEN FULL_INIT_TAC THEN
  RULE_ASSUM_TAC(CONV_RULE(ONCE_DEPTH_CONV NUM_MULT_CONV)) THEN
  ENSURES_FINAL_STATE_TAC THEN ASM_REWRITE_TAC[] THEN
  DISCHARGE_SAFETY_PROPERTY_TAC;;

(*** The exec theorem for the range of a loop: from its head to its exit ***)
(*** (a name of the layout or a numeral for each, as in inline_sign_pack.ml, ***)
(*** which defines it in the same way; either may be loaded last)          ***)

let INLINE_LOOP_EXEC loop exit =
  let n s = try int_of_string s with Failure _ -> layout s in
  ARM_MK_EXEC_RANGES_RULE mldsa_native_libmldsa_clang23_O3_mono_reduced_ram_mc
   [(n loop, n exit)];;

(* ------------------------------------------------------------------------- *)
(* poly_caddq, as clang -O3 has inlined it (19 instances): a + q if a is     *)
(* negative, one coefficient per iteration, with the registers (canonical    *)
(* order of appearance in the loop, as in shapes.py)                         *)
(*   R0 = temporary, R1 = a, R2 = byte offset (from 0), R3, R4 = temporaries, *)
(*   R5 = q = 8380417                                                        *)
(*     ldrsw R0, [R1, R2]; mov w.R3, w.R0; lsr R0, R0, #31;                  *)
(*     add w.R4, w.R3, w.R5; bic w.R3, w.R3, w.R0; and w.R0, w.R4, w.R0;     *)
(*     orr w.R0, w.R0, w.R3; str w.R0, [R1, R2]; add R2, R2, #4;             *)
(*     cmp R2, #0x400; b.ne                                                  *)
(* ------------------------------------------------------------------------- *)

let INLINE_CADDQ_LANE_TAC =
  FIRST_X_ASSUM(fun th ->
    let l,r = dest_eq(concl th) in
    if can (term_match [] `read (memory :> bytes32 a) s`) l &&
       free_in `x:num->int32` r then
      let v = `(x:num->int32) i` and y = genvar `:int32` in
      let lemma = prove
       (mk_forall(y,mk_eq(subst[y,v] r,mk_comb(`mld_caddq`,y))),
        GEN_TAC THEN REWRITE_TAC[mld_caddq; GSYM MSB_IVAL; DIMINDEX_32] THEN
        CONV_TAC NUM_REDUCE_CONV THEN BITBLAST_TAC) in
      ASSUME_TAC(REWRITE_RULE[lemma] th)
    else NO_TAC);;

let INLINE_CADDQ_LOOP_TERM mc loop exit (rs:string list) =
  let r k = List.nth rs k in
  parse_term(Printf.sprintf
   "exists f_events.
      forall e a (x:num->int32) pc.
        aligned 4096 (word pc:int64) /\\ pc + libmldsa_size <= 2 EXP 64 /\\
        ALL (nonoverlapping (a,1024)) [(word pc,libmldsa_size)]
        ==> ensures arm
             (\\s. aligned_bytes_loaded s (word pc) %s /\\
                  read PC s = word (pc + %s) /\\
                  read %s s = a /\\ read %s s = word 0 /\\
                  read %s s = word 8380417 /\\
                  (!i. i < 256
                       ==> read(memory :> bytes32(word_add a (word(4 * i))))
                             s = x i) /\\
                  read events s = e)
             (\\s. read PC s = word (pc + %s) /\\
                  read %s s = word 1024 /\\
                  (!i. i < 256
                       ==> read(memory :> bytes32(word_add a (word(4 * i))))
                             s = mld_poly_caddq x i) /\\
                  (exists e2.
                     read events s = APPEND e2 e /\\
                     e2 = f_events a pc /\\
                     memaccess_inbounds e2 [a,1024] [a,1024]))
             (MAYCHANGE [PC; %s; %s; %s; %s] ,, MAYCHANGE SOME_FLAGS ,,
              MAYCHANGE [events] ,, MAYCHANGE [memory :> bytes(a,1024)])"
   mc loop (r 1) (r 2) (r 5) exit (r 2) (r 0) (r 2) (r 3) (r 4));;

let INLINE_CADDQ_LOOP mc exec loop exit (rs:string list) =
  let r k = List.nth rs k in
  let tm = INLINE_CADDQ_LOOP_TERM mc loop exit rs in
  let inv = parse_term(Printf.sprintf
   "\\i s. read %s s = a /\\ read %s s = word(4 * i) /\\
          read %s s = word 8380417 /\\
          (!j. i <= j /\\ j < 256
               ==> read(memory :> bytes32(word_add a (word(4 * j)))) s =
                   (x:num->int32) j) /\\
          (!j. j < i
               ==> read(memory :> bytes32(word_add a (word(4 * j)))) s =
                   mld_caddq (x j))" (r 1) (r 2) (r 5)) in
  prove(tm,
  CONCRETIZE_F_EVENTS_TAC
   `\(a:int64) (pc:num).
      APPEND (f_ev_epil a pc)
       (APPEND (ENUMERATEL 256 (\i. f_ev_loop a pc i)) (f_ev_prol a pc))
    :(uarch_event)list` THEN
  REPEAT META_EXISTS_TAC THEN
  MAP_EVERY X_GEN_TAC [`e:(uarch_event)list`; `a:int64`; `x:num->int32`;
                       `pc:num`] THEN
  REWRITE_TAC[NONOVERLAPPING_CLAUSES; ALL; SOME_FLAGS; mld_poly_caddq;
              fst exec] THEN
  DISCH_THEN(REPEAT_TCL CONJUNCTS_THEN ASSUME_TAC) THEN
  ENSURES_EVENTS_WHILE_UP2_TAC `256` (parse_term("pc + "^loop))
   (parse_term("pc + "^exit)) inv THEN
  REPEAT CONJ_TAC THENL
   [ARITH_TAC;
    FULL_INIT_TAC THEN
    ENSURES_FINAL_STATE_TAC THEN ASM_REWRITE_TAC[] THEN
    REWRITE_TAC[MULT_CLAUSES; CONJUNCT1 LT; LE_0; WORD_ADD_0] THEN
    ASM_REWRITE_TAC[] THEN DISCHARGE_SAFETY_PROPERTY_TAC;

    X_GEN_TAC `i:num` THEN STRIP_TAC THEN REWRITE_TAC[] THEN
    FULL_INIT_TAC THEN
    FIRST_X_ASSUM(MP_TAC o GEN_REWRITE_RULE I [ONE_INPUT_SPLIT] o
      check (fun th -> is_forall(concl th) &&
        free_in `x:num->int32` (concl th) &&
        not(free_in `mld_caddq` (concl th)))) THEN
    ASM_REWRITE_TAC[] THEN STRIP_TAC THEN
    ARM_STEPS_TAC exec (1--8) THEN
    INLINE_CADDQ_LANE_TAC THEN
    ARM_STEPS_TAC exec (9--11) THEN
    FULL_FINAL_TAC [ONE_OUTPUT_SPLIT];

    INLINE_EXIT_TAC]);;

(* ------------------------------------------------------------------------- *)
(* The prologue of a function with a frame of more than 4096 bytes: clang    *)
(* computes x9 = (sp - K) & ~31, lowers sp by 4096 and probes the stack with *)
(* LDR XZR, [sp] in a loop (SUB SP, SP, #4096; CMP SP, X9; B.GT). The flags  *)
(* are those of signed comparisons of addresses, so deciding the branches    *)
(* needs that the stack region does not straddle 2^63 or 0: statements       *)
(* assume 32768 <= val stackpointer /\ val stackpointer < 2 EXP 63 (the     *)
(* probes compare addresses down to sp - 16544).                              *)
(*                                                                           *)
(* The tools: ALIGNED_WORD_AND_N k (aligned 2^k x <=> x && word(2^k-1) = 0), *)
(* IVAL_SP_SUB (ival(word_sub sp (word k)) = &(val sp) - &k), and PROBE_TAC   *)
(* exec n, which simulates instruction n and, if the new PC is a condition   *)
(* on comparisons of words word_sub stackpointer (word k), decides it. The   *)
(* masking of X9 is done by the lemma generated for the case of alignment    *)
(* (see ALIGN_FRAME_LEMMA).                                                  *)
(* ------------------------------------------------------------------------- *)

let ALIGNED_WORD_AND_N k =
  let m = (1 lsl k) in
  prove(parse_term(Printf.sprintf
   "!x:int64. aligned %d x <=> word_and x (word %d) = word 0" m (m-1)),
  GEN_TAC THEN REWRITE_TAC[aligned; DIMINDEX_64] THEN
  CONV_TAC NUM_REDUCE_CONV THEN
  CONV_TAC(ONCE_DEPTH_CONV DIVIDES_CONV) THEN REWRITE_TAC[] THEN
  MP_TAC(ISPECL [`x:int64`; mk_small_numeral k] (CONJUNCT1 WORD_AND_MASK_WORD)) THEN
  CONV_TAC(ONCE_DEPTH_CONV NUM_REDUCE_CONV) THEN DISCH_THEN SUBST1_TAC THEN
  REWRITE_TAC[DIVIDES_MOD; GSYM VAL_EQ_0; VAL_WORD; DIMINDEX_64] THEN
  SIMP_TAC[MOD_LT; ARITH_RULE `x MOD 16 < 16`; ARITH_RULE `x MOD 32 < 32`;
           ARITH_RULE `x < 16 ==> x < 2 EXP 64`;
           ARITH_RULE `x < 32 ==> x < 2 EXP 64`]);;

let ALIGNED_16_WORD_AND = ALIGNED_WORD_AND_N 4;;
let ALIGNED_32_WORD_AND = ALIGNED_WORD_AND_N 5;;

let IVAL_SP_SUB = prove
 (`!s:int64 k. k <= val s /\ val s < 2 EXP 63 /\ k < 2 EXP 63
               ==> ival(word_sub s (word k)) = &(val s) - &k`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN `val(word_sub s (word k):int64) = val s - k` ASSUME_TAC THENL
   [ASM_SIMP_TAC[VAL_WORD_SUB_CASES; VAL_WORD; DIMINDEX_64; MOD_LT;
                 ARITH_RULE `k < 2 EXP 63 ==> k < 2 EXP 64`] THEN
    ASM_ARITH_TAC;
    ALL_TAC] THEN
  SUBGOAL_THEN `val(word_sub s (word k):int64) < 2 EXP (dimindex(:64) - 1)`
   ASSUME_TAC THENL
   [REWRITE_TAC[DIMINDEX_64] THEN CONV_TAC NUM_REDUCE_CONV THEN ASM_ARITH_TAC;
    ALL_TAC] THEN
  ASM_SIMP_TAC[IVAL_EQ_VAL] THEN
  ASM_SIMP_TAC[GSYM INT_OF_NUM_SUB]);;

(*** For the frame constants (a, b) of the prologue
     sub x9, sp, #a; sub x9, x9, #b; and x9, x9, #~31 after the stores that
     lower sp by 160: the value of X9 in each case of the alignment of sp. ***)

let ALIGN_FRAME_LEMMAS a b =
  let tm32 = parse_term(Printf.sprintf
   "word_and (s:int64) (word 31) = word 0
    ==> word_and (word_sub (word_sub (word_sub s (word 160)) (word %d)) (word %d))
                 (word 18446744073709551584) = word_sub s (word %d)"
   a b (160 + a + b))
  and tm16 = parse_term(Printf.sprintf
   "word_and (s:int64) (word 15) = word 0 /\\ ~(word_and s (word 31) = word 0)
    ==> word_and (word_sub (word_sub (word_sub s (word 160)) (word %d)) (word %d))
                 (word 18446744073709551584) = word_sub s (word %d)"
   a b (160 + a + b + 16)) in
  BITBLAST_RULE tm32, BITBLAST_RULE tm16;;

let SP_SUBSUB = INT_ARITH `!v a b:int. v - a - (v - b) = b - a`;;

let SP_NORM_CONV =
  GEN_REWRITE_CONV TOP_DEPTH_CONV
   [WORD_RULE `word_sub (word_sub (s:int64) (word a)) (word b) =
               word_sub s (word(a+b))`;
    WORD_RULE `word_sub (word_sub (s:int64) a) (word_sub s b) = word_sub b a`]
  THENC DEPTH_CONV NUM_ADD_CONV THENC DEPTH_CONV WORD_RED_CONV;;

let SP_IVAL_TAC =
  W(fun (asl,w) ->
    let all = list_mk_conj(w :: map (concl o snd) asl) in
    let pat = `ival(word_sub (stackpointer:int64) (word k))` in
    let tms = setify(find_terms (can (term_match [] pat)) all) in
    MAP_EVERY (fun t ->
      let k = rand(rand(rand t)) in
      MP_TAC(SPECL [`stackpointer:int64`; k] IVAL_SP_SUB) THEN
      ANTS_TAC THENL [ASM_ARITH_TAC; ALL_TAC] THEN
      DISCH_THEN(fun th -> RULE_ASSUM_TAC(REWRITE_RULE[th]))) tms);;

let PROBE_CONV =
  REWRITE_CONV[SP_SUBSUB] THENC ONCE_DEPTH_CONV INT_SUB_CONV THENC
  REWRITE_CONV[INT_OF_NUM_EQ; INT_OF_NUM_LT; ARITH_EQ; ARITH_LT; ARITH_LE;
               INT_LT_REFL; INT_OF_NUM_LE];;

let PROBE_PC_TAC =
  RULE_ASSUM_TAC(fun th ->
    let l,r = try dest_eq(concl th) with Failure _ -> `T`,`T` in
    if is_comb l && is_comb(rator l) && is_const(rator(rator l)) &&
       fst(dest_const(rator(rator l))) = "read" &&
       rand(rator l) = `PC` && free_in `stackpointer:int64` r
    then REWRITE_RULE[COND_CLAUSES]
          (CONV_RULE(RAND_CONV(ONCE_DEPTH_CONV(fun t ->
            if type_of t = bool_ty && free_in `stackpointer:int64` t
            then PROBE_CONV t else failwith ""))) th)
    else th);;

let PROBE_TAC exec n =
  ARM_STEPS_TAC exec [n] THEN
  RULE_ASSUM_TAC(CONV_RULE(ONCE_DEPTH_CONV SP_NORM_CONV)) THEN
  SP_IVAL_TAC THEN PROBE_PC_TAC;;
