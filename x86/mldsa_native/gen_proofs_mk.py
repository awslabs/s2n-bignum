#!/usr/bin/env python3

# Generate the proofs.mk of a build of mldsa-native's libmldsa.so, which
# x86/Makefile includes (see mldsa_native/README.md): the object files of
# the transcriptions in mldsa_native/<build>, the proofs in
# proofs/mldsa_native/<build>, and the dependencies of each proof on the
# files that it loads with `needs` and on the object files that they read.
#
# Every .ml file of proofs/mldsa_native/<build> is a proof, except layout.ml
# and the spec files X_spec.ml, which the proof file X_proof.ml and the spec
# files of the callers load (see proofs/mldsa_native/relative.ml). The proof
# link.ml, generated by gen_link.py, loads all the proof files X_proof.ml
# in one session.
#
# Usage, in s2n-bignum's x86 directory:
#
#   python3 mldsa_native/gen_proofs_mk.py gcc12_O2 \
#     > mldsa_native/gcc12_O2/proofs.mk

import os, re, sys

def needs(path):
    """The files that path loads with needs, as paths relative to the x86
    directory: the proofs and tools under arm/proofs, and the
    specifications common/mldsa_native*.ml and common/fips204*.ml."""
    if not os.path.exists(path):
        return []
    out = []
    for l in open(path):
        m = re.match(r'\s*needs\s+"x86/(proofs/[^"]+)"', l)
        if m:
            out.append(m.group(1))
        m = re.match(r'\s*needs\s+"(common/(mldsa_native|fips204)[^"]*)"', l)
        if m:
            out.append('../' + m.group(1))
    return out

def objects_read(path, src):
    """The object files of the build that the file reads, e.g. with
    define_from_elf."""
    pat = re.compile(r'"x86/(%s/[A-Za-z0-9_]+\.o)"' % re.escape(src))
    return pat.findall(open(path).read()) if os.path.exists(path) else []

def closure(prf, src, path):
    """The files that path loads, directly or not, other than base.ml and
    what it loads, and the object files of the build that they read."""
    deps = []; todo = needs(path)
    objs = objects_read(path, src)
    while todo:
        d = todo.pop(0)
        if d in deps:
            continue
        if d.startswith(prf + '/') or d.startswith('proofs/utils/') or \
           (d.startswith('proofs/mldsa_native/') and d.count('/') == 2) or \
           d.startswith('../common/mldsa_native') or \
           d.startswith('../common/fips204'):
            deps.append(d); todo += needs(d)
            objs += [o for o in objects_read(d, src) if o not in objs]
    return deps, sorted(set(objs))

def main():
    if len(sys.argv) != 2:
        sys.exit('usage: gen_proofs_mk.py BUILD')
    build = sys.argv[1]
    src = 'mldsa_native/%s' % build
    prf = 'proofs/mldsa_native/%s' % build
    objs = sorted(f[:-2] for f in os.listdir(src) if f.endswith('.S'))
    proofs = sorted(f[:-3] for f in os.listdir(prf)
                    if f.endswith('.ml') and f != 'layout.ml' and
                       not f.endswith('_spec.ml'))
    read = set()
    for f in os.listdir(prf):
        if f.endswith('.ml'):
            read |= set(objects_read('%s/%s' % (prf, f), src))
    missing = [o for o in objs if '%s/%s.o' % (src, o) not in read]
    if missing:
        sys.exit('gen_proofs_mk.py: no proofs read ' + ' '.join(missing))
    out = ['# Generated by mldsa_native/gen_proofs_mk.py %s from the needs of '
           'the' % build,
           '# proofs in %s. Do not edit.' % prf, '']
    def lst(var, items, sfx):
        out.append('%s += \\' % var)
        for i, x in enumerate(items):
            out.append('  %s/%s%s%s' % (src, x, sfx,
                                      ' \\' if i + 1 < len(items) else ''))
        out.append('')
    lst('MLDSA_NATIVE_OBJ', objs, '.o')
    lst('MLDSA_NATIVE_PROOFS', proofs, '')
    for p in proofs:
        deps, os_ = closure(prf, src, '%s/%s.ml' % (prf, p))
        deps = deps + os_
        if deps:
            out.append('%s/%s.native: \\' % (src, p))
            out += ['  %s%s' % (d, ' \\' if i + 1 < len(deps) else '')
                    for i, d in enumerate(deps)]
    sys.stdout.write('\n'.join(out) + '\n')

if __name__ == '__main__':
    main()
