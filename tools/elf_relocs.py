#!/usr/bin/env python3

# Generate the HOL Light definition of the relocated slots of an ELF shared
# object: the 64-bit words that the dynamic loader writes into the binary
# when it loads it at a base address pc, as a function of pc and of the
# addresses of the imported symbols.
#
# Usage: elf_relocs.py [--isa ISA] [--readelf READELF] [--title TEXT]
#                      BINARY NAME > RELOCS.ml
#
# For example, in s2n-bignum's arm directory:
#
#   python3 ../tools/elf_relocs.py <snappy-build>/gcc12_O2/libsnappy.so \
#     snappy_libsnappy_gcc12_O2 > proofs/snappy/gcc12_O2/relocs.ml
#
# The file defines
#
#   NAME_relocated (pc:num) (imp:string->int64) : (int64 # int64) list
#
# as the list, by address, of the pairs (word (pc + OFF), V) of the address
# of each relocated slot, OFF being its offset in the binary, and the
# value V that the loader writes there, which is, for an addend A and a
# symbol "sym" (its name in the dynamic symbol table, without a version):
#
#   RELATIVE                word (pc + A)
#   GLOB_DAT, JUMP_SLOT     imp "sym"
#   ABS64 (x86-64: 64)      imp "sym" if A = 0, else
#                           word_add (imp "sym") (word A), or
#                           word_sub (imp "sym") (word (-A)) if A < 0
#
# Here imp gives the address of each imported symbol, which a theorem about
# the loaded binary quantifies over. The relocation types are those of the
# instruction set (--isa aarch64, the default, or x86_64); any other
# dynamic relocation is an error. A slot relocated twice is an error too.
# In the binary, the slots of GLOB_DAT and JUMP_SLOT relocations hold
# their own address or 0 before loading, so the list is needed to know
# their contents. It says nothing about the other bytes of the writable
# segment, which the binary gives.

import argparse, hashlib, os, re, subprocess, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from elf_layout import dynamic_relocations, run

KINDS = {
    'aarch64': {'R_AARCH64_RELATIVE': 'relative', 'R_AARCH64_GLOB_DAT': 'symbol',
                'R_AARCH64_JUMP_SLOT': 'symbol', 'R_AARCH64_ABS64': 'abs64'},
    'x86_64': {'R_X86_64_RELATIVE': 'relative', 'R_X86_64_GLOB_DAT': 'symbol',
               'R_X86_64_JUMP_SLOT': 'symbol', 'R_X86_64_64': 'abs64'}}

def value(kind, sym, add):
    if kind == 'relative':
        return 'word (pc + 0x%x)' % add
    s = 'imp "%s"' % sym
    if kind == 'symbol':
        if add != 0:
            raise ValueError('a GLOB_DAT or JUMP_SLOT relocation with an addend')
        return s
    if add == 0:
        return s
    if add > 0:
        return 'word_add (%s) (word 0x%x)' % (s, add)
    return 'word_sub (%s) (word 0x%x)' % (s, -add)

def main():
    ap = argparse.ArgumentParser(description='Generate the relocated slots of an ELF shared object')
    ap.add_argument('binary')
    ap.add_argument('name', help='the prefix of the HOL constant, NAME_relocated')
    ap.add_argument('--isa', default='aarch64', choices=sorted(KINDS))
    ap.add_argument('--readelf', default=os.environ.get('READELF', 'readelf'))
    ap.add_argument('--title', help='what the binary is, for the header')
    args = ap.parse_args()
    kinds = KINDS[args.isa]
    rows = []; seen = set()
    for off, typ, sym, add in dynamic_relocations(args.readelf, args.binary):
        if typ not in kinds:
            sys.exit('elf_relocs.py: relocation %s at 0x%x is not supported' % (typ, off))
        if off in seen:
            sys.exit('elf_relocs.py: two relocations at 0x%x' % off)
        if kinds[typ] == 'relative' and sym is not None:
            sys.exit('elf_relocs.py: a RELATIVE relocation with a symbol at 0x%x' % off)
        if kinds[typ] != 'relative' and sym is None:
            sys.exit('elf_relocs.py: no symbol for the relocation at 0x%x' % off)
        if off % 8:
            sys.exit('elf_relocs.py: the slot at 0x%x is not aligned' % off)
        seen.add(off)
        rows.append((off, typ, sym, add, value(kinds[typ], sym, add)))
    rows.sort()
    digest = hashlib.sha256(open(args.binary, 'rb').read()).hexdigest()
    name = args.name + '_relocated'
    o = sys.stdout
    o.write('(*\n * Copyright Amazon.com, Inc. or its affiliates. All Rights Reserved.\n'
            ' * SPDX-License-Identifier: Apache-2.0 OR ISC OR MIT-0\n *)\n\n')
    o.write('(* %s *)\n' % ('=' * 73))
    import textwrap
    text = ('The slots of %s%s that the dynamic loader relocates, with the values '
            'that it writes there when it loads the binary at the base pc, the '
            'address of each imported symbol "sym" being imp "sym". %d relocations. '
            'Generated by tools/elf_relocs.py (which explains the format) from the '
            'binary with SHA-256 %s. Do not edit it by hand.' %
            (os.path.basename(args.binary), ' (%s)' % args.title if args.title else '',
             len(rows), digest))
    for l in textwrap.wrap(text, 73, break_on_hyphens=False):
        o.write('(* %-73s *)\n' % l)
    o.write('(* %s *)\n\n' % ('=' * 73))
    o.write('needs "Library/words.ml";;\n\n')
    o.write('(* %-73s *)\n' % 'The relocations, as offset, type, symbol + addend:')
    o.write('(* %-73s *)\n' % '')
    for off, typ, sym, add, v in rows:
        o.write('(* %-73s *)\n' % ('  0x%05x  %-20s %s' % (
            off, typ, (sym + ' + 0x%x' % add) if sym else '0x%x' % add))[:73])
    o.write('\n')
    o.write('let %s = new_definition\n `%s (pc:num) (imp:string->int64) =\n   [' %
            (name, name))
    lines = ['(word (pc + 0x%x):int64, %s:int64)' % (off, v)
             for off, typ, sym, add, v in rows]
    o.write(';\n    '.join(lines))
    o.write(']`;;\n')

if __name__ == '__main__':
    main()
