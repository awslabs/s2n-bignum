#!/usr/bin/env python3

# Generate the proofs.mk of a build of mlkem-native, mldsa-native or another family, which
# the Makefile of s2n-bignum's arm or x86 directory includes: the object
# files of the transcriptions in <family>/<build>, the proofs in
# proofs/<family>/<build>, and the dependencies of each proof on the files
# that it loads with `needs` (other than base.ml and what it loads) and on
# the object files that they read.
#
# Every .ml file of proofs/<family>/<build> is a proof, except layout.ml and
# the spec files X_spec.ml, which the proof file X_proof.ml and the spec
# files of the callers load (see common/relative.ml). The proof link.ml,
# generated by native_link.py, loads all the proof files X_proof.ml in one
# session.
#
# Usage, in s2n-bignum's arm or x86 directory:
#
#   python3 ../tools/native_proofs_mk.py mldsa_native gcc12_O2 \
#     > mldsa_native/gcc12_O2/proofs.mk

import os, re, sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from native_link import file_needs

LOADT = re.compile(r'\s*loadt\s+"([^"]+)"')

def base_files(isa):
    """The files that base.ml loads: they are not dependencies."""
    return (set(file_needs('proofs/base.ml')) |
            set(m.group(1) for l in open('proofs/base.ml')
                for m in [LOADT.match(l)] if m) | {'%s/proofs/base.ml' % isa})

def needs(isa, path):
    """The files that path loads with needs, as paths relative to the
    directory of the instruction set: those under proofs/, and those of
    common/ (as ../common/...)."""
    if not os.path.exists(path):
        return []
    return [l[len(isa) + 1:] if l.startswith(isa + '/proofs/') else '../' + l
            for l in file_needs(path)
            if l.startswith(isa + '/proofs/') or l.startswith('common/')]

def objects_read(isa, path, src):
    """The object files of the build that the file reads, e.g. with
    define_from_elf."""
    pat = re.compile(r'"%s/(%s/[A-Za-z0-9_]+\.o)"' % (isa, re.escape(src)))
    return pat.findall(open(path).read()) if os.path.exists(path) else []

def closure(isa, skip, src, path):
    """The files that path loads, directly or not, other than base.ml and
    what it loads, and the object files of the build that they read."""
    deps = []; todo = needs(isa, path)
    objs = objects_read(isa, path, src)
    while todo:
        d = todo.pop(0)
        if d in deps:
            continue
        name = d[3:] if d.startswith('../') else '%s/%s' % (isa, d)
        if name in skip or not os.path.exists(d):
            continue
        deps.append(d); todo += needs(isa, d)
        objs += [o for o in objects_read(isa, d, src) if o not in objs]
    return deps, sorted(set(objs))

def main():
    if len(sys.argv) != 3 or not os.path.isdir(os.path.join('proofs', sys.argv[1])):
        sys.exit('usage: native_proofs_mk.py FAMILY BUILD (run in arm/ or x86/, '
                 'with proofs/FAMILY/BUILD present)')
    family, build = sys.argv[1], sys.argv[2]
    isa = os.path.basename(os.getcwd())
    if isa not in ('arm', 'x86'):
        sys.exit('native_proofs_mk.py: run it in the arm or x86 directory')
    var = family.upper()
    src = '%s/%s' % (family, build)
    prf = 'proofs/%s/%s' % (family, build)
    skip = base_files(isa)
    objs = sorted(f[:-2] for f in os.listdir(src) if f.endswith('.S'))
    proofs = sorted(f[:-3] for f in os.listdir(prf)
                    if f.endswith('.ml') and f != 'layout.ml' and
                       not f.endswith('_spec.ml'))
    read = set()
    for f in os.listdir(prf):
        if f.endswith('.ml'):
            read |= set(objects_read(isa, '%s/%s' % (prf, f), src))
    missing = [o for o in objs if '%s/%s.o' % (src, o) not in read]
    if missing:
        sys.exit('native_proofs_mk.py: no proofs read ' + ' '.join(missing))
    out = ['# Generated by tools/native_proofs_mk.py %s %s from the needs of the'
           % (family, build),
           '# proofs in %s. Do not edit.' % prf, '']
    def lst(v, items, sfx):
        out.append('%s += \\' % v)
        for i, x in enumerate(items):
            out.append('  %s/%s%s%s' % (src, x, sfx, ' \\' if i + 1 < len(items) else ''))
        out.append('')
    lst(var + '_OBJ', objs, '.o')
    lst(var + '_PROOFS', proofs, '')
    for p in proofs:
        deps, os_ = closure(isa, skip, src, '%s/%s.ml' % (prf, p))
        deps = deps + os_
        if deps:
            out.append('%s/%s.native: \\' % (src, p))
            out += ['  %s%s' % (d, ' \\' if i + 1 < len(deps) else '') for i, d in enumerate(deps)]
    sys.stdout.write('\n'.join(out) + '\n')

if __name__ == '__main__':
    main()
