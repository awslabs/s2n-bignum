let snappy_hex_bytes s =
  if s = "-" then [] else
  List.init (String.length s / 2)
    (fun i -> int_of_string ("0x" ^ String.sub s (2 * i) 2));;

let snappy_mk_bytelist l =
  mk_list(map (fun n -> mk_comb(`word:num->byte`,mk_small_numeral n)) l,
          `:byte`);;

let snappy_check_vector line =
  match String.split_on_char ' ' line with
    [inp; outp; hdr; vst; ust] ->
      let l = snappy_mk_bytelist(snappy_hex_bytes inp) in
      let ev t = rand(concl(SNAPPY_EVAL_CONV t)) in
      let dec = ev (mk_comb(`snappy_decode`,l)) in
      let dec_ok =
        if outp = "NONE" then dec = `NONE:(byte list)option` else
        dec = mk_comb(`SOME:byte list->(byte list)option`,
                      snappy_mk_bytelist(snappy_hex_bytes outp)) in
      let hd = ev (mk_comb(`snappy_header`,l)) in
      let hd_ok =
        if hdr = "NONE" then hd = `NONE:num option` else
        hd = mk_comb(`SOME:num->num option`,
                     mk_numeral(num_of_string hdr)) in
      let vs = ev (mk_comb(`snappy_validate_status`,l)) in
      let vs_ok = vs = mk_small_numeral(int_of_string vst) in
      let us_ok =
        if hdr = "NONE" then true else
        let m = num_of_string hdr in
        let us = ev (list_mk_comb(`snappy_uncompress_status`,
                                  [l; mk_numeral m])) in
        let us1 =
          if m = num 0 then true else
          ev (list_mk_comb(`snappy_uncompress_status`,
                           [l; mk_numeral(m -/ num 1)])) = `2` in
        us = mk_small_numeral(int_of_string ust) && us1 in
      dec_ok && hd_ok && vs_ok && us_ok
  | _ -> failwith "snappy_check_vector: bad line";;

let snappy_test_failures =
  filter (fun l -> not(snappy_check_vector l)) snappy_test_vectors;;

Printf.printf "snappy_format tests: %d vectors, %d failures\n%!"
  (length snappy_test_vectors) (length snappy_test_failures);;

List.iter (Printf.printf "FAILED VECTOR: %s\n%!") snappy_test_failures;;

if snappy_test_failures <> [] then failwith "snappy_format tests failed";;
