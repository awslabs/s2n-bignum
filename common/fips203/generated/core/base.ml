(* ========================================================================= *)
(* Common context for the equivalence proofs between the FIPS 203 model     *)
(* generated by the FIPS pseudocode compiler (common/fips203/generated/) and    *)
(* the handwritten model common/fips203/fips203.ml, with the properties of  *)
(* the handwritten model in common/fips20[23]/properties/. Load from the    *)
(* repository root.                                                          *)
(*                                                                           *)
(* Both models are loaded into one session. They use the same SHA-3         *)
(* functions: the generated files bind their hash externals to sha3_256,    *)
(* sha3_512, shake128 and shake256, and the vendored compiler/fips202.ml    *)
(* equals common/fips202/fips202.ml apart from a header comment. It is      *)
(* loaded a second time on purpose: HOL Light only accepts a redefinition   *)
(* of a constant if the definition is identical, so a differing definition  *)
(* would make the load fail (25 benign redefinition warnings are expected). *)
(*                                                                           *)
(* This file and the abstraction functions below are proof machinery: none  *)
(* of the statements in ../fips203_equivalence.ml mentions them.            *)
(* ========================================================================= *)

needs "common/fips203/properties/fips203_properties.ml";;

(* The generated model: prelude, SHA-3, model, proof obligations. The       *)
(* paths are literal so that HOL Light native-code builds can follow them.  *)

loadt "common/fips203/generated/core/compiler/fips_hol_prelude.ml";;
loadt "common/fips203/generated/core/compiler/fips202.ml";;
type_invention_error := true;;
loadt "common/fips203/generated/fips203_generated.ml";;
loadt "common/fips203/generated/core/compiler/fips203_obligations.ml";;
type_invention_error := false;;

(* ------------------------------------------------------------------------- *)
(* Abstraction functions from generated values to handwritten ones.         *)
(*                                                                           *)
(*  fz z          the integer value of a generated Z_q element               *)
(*  zarr l        a list of Z_q elements as an array num->int               *)
(*  zpoly l       a list of Z_q elements as an element of R_q                *)
(*  zqlist a      the canonical generated list for the array a (reduced)   *)
(*  zq_list_ok l  l has 256 entries, all of them < q                         *)
(*  zvec k v      the generated vector of k polynomials v 0, ..., v (k-1)   *)
(*  zmat k a      the generated k x k matrix with entries a i j, row-major  *)
(* ------------------------------------------------------------------------- *)

let fz = new_definition
 `fz (z:fips203_zq) = &(residue_rep (fips203_zq_residue z)):int`;;

let zarr = new_definition
 `zarr (l:fips203_zq list) = \i. fz (EL i l)`;;

let zpoly = new_definition
 `zpoly (l:fips203_zq list) = mlkem_poly (zarr l)`;;

let zqlist = new_definition
 `zqlist (a:num->int) =
    list_of_seq (\i. FIPS203_Zq (residue_of_int_mod (a i))) 256`;;

let zq_list_ok = new_definition
 `zq_list_ok (l:fips203_zq list) <=>
    LENGTH l = 256 /\ !i. i < 256 ==> fz (EL i l) < &3329`;;

let zvec = new_definition
 `zvec k (v:num->fips203_zq list) =
    (Common_Vec (list_of_seq (\i. FIPS203_Poly (v i)) k)
     :(A,(P)fips203_poly)common_vec)`;;

let zmat = new_definition
 `zmat k (a:num->num->fips203_zq list) =
    (Common_Mat
      (FIPS_Matrix
        (list_of_seq (\n. FIPS203_Poly (a (n DIV k) (n MOD k))) (k * k)))
     :(R,C,(P)fips203_poly)common_mat)`;;

