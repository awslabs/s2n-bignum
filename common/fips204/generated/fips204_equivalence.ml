(* ========================================================================= *)
(* The statements of the equivalence between the FIPS 204 model generated by *)
(* the FIPS pseudocode compiler (fips204_generated.ml) and the handwritten   *)
(* model (common/fips204/fips204.ml).                                        *)
(*                                                                           *)
(* For the right input lengths, the generated ML-DSA function returns what   *)
(* the handwritten function computes. The proofs and their tools are in      *)
(* core/; none of the statements below mentions anything from there, except  *)
(* the definitions that they use: xof_ok, top_prehash, lift_sign_result,     *)
(* lift_sign_internal_result, lift_verify_result and lift_verify_bool (see   *)
(* core/README.md).                                                          *)
(*                                                                           *)
(* Reading the statements:                                                   *)
(*  - The handwritten signing functions take a bound on the attempts of the  *)
(*    signing loop (Algorithm 7); all statements use NONE, the unbounded     *)
(*    search of FIPS 204. They return an mldsa_sign_result:                  *)
(*    MLDSA_Sign_Success sg, MLDSA_Sign_Error_BadContext (a context of more  *)
(*    than 255 bytes) or MLDSA_Sign_Error_OutOfAttempts (no attempt of the   *)
(*    loop is accepted). The verification functions return an                *)
(*    mldsa_verify_result: MLDSA_Verify_Success,                             *)
(*    MLDSA_Verify_Error_InvalidSignature or MLDSA_Verify_Error_BadContext.  *)
(*  - lift_sign_result and lift_verify_result map these to the results of    *)
(*    the generated functions that have a native_bottom: Success is          *)
(*    Value (Native_Value sg) or Value (Native_Value T), InvalidSignature is *)
(*    Value (Native_Value F), BadContext is Value Native_Bottom, and         *)
(*    OutOfAttempts is Nontermination. The generated internal functions      *)
(*    return a bare value: lift_sign_internal_result maps Success sg to      *)
(*    Value sg and OutOfAttempts to Nontermination (BadContext, which the    *)
(*    handwritten internal functions never return, to Fault Explicit_Abort), *)
(*    and lift_verify_bool maps Success to Value T and InvalidSignature to   *)
(*    Value F (and BadContext, which hash_mldsa_verify returns for a long    *)
(*    context, to Value F: the generated HashML-DSA verification returns     *)
(*    false for it).                                                         *)
(*  - ent is the entropy source of the generated KeyGen and Sign: ent 0 is   *)
(*    its first request for random bytes. As in FIPS 203, the statements     *)
(*    assume that the random generator does not fail (ent 0 = SOME ...).     *)
(*    The generated functions return Native_Bottom if it does, which has no  *)
(*    counterpart in the handwritten model.                                  *)
(*  - xof_ok: the uninterpreted shake256_bits and shake128_bits of the       *)
(*    generated file are SHAKE256 and SHAKE128 of common/fips202/fips202.ml  *)
(*    on bit strings bits_of_bytes s.                                        *)
(*  - Messages are bits_of_bytes m for a byte string m. Keys and signatures  *)
(*    have the exact lengths of the parameter set. The pre-hash functions of *)
(*    HashML-DSA stay uninterpreted: the digest is top_prehash n M.          *)
(*  - Messages that are not a whole number of bytes are not covered.         *)
(* ========================================================================= *)

