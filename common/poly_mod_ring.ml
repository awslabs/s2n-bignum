let INT_CONG_ISUM = prove
 (`!n f g (s:A->bool).
        FINITE s /\ (!x. x IN s ==> (f x == g x) (mod n))
        ==> (isum s f == isum s g) (mod n)`,
  REPEAT STRIP_TAC THEN
  MATCH_MP_TAC(BETA_RULE(ISPEC `(\x y:int. (x == y) (mod n))`
    ISUM_RELATED)) THEN
